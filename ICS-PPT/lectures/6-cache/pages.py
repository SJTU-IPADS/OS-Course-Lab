def simulate_misses(blocks, slots=4):
    """Classify each reference in a direct-mapped cache of `slots` blocks. Block b goes to slot b % slots.

    Hit: the slot holds the block. Otherwise a cold miss on the first reference to the block.
    For a block referenced before, a capacity miss when at least `slots` distinct other blocks
    were referenced since its previous reference, and a conflict miss when fewer were.
    """
    held = [None] * slots
    last = {}                    # block -> index of its previous reference
    out = []
    for idx, block in enumerate(blocks):
        slot = block % slots
        if held[slot] == block:
            out.append("命中")
        elif block not in last:
            out.append("冷")
        else:
            others = set(blocks[last[block] + 1:idx]) - {block}
            out.append("容量" if len(others) >= slots else "冲突")
        held[slot] = block
        last[block] = idx
    return out


