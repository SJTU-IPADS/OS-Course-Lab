# 上一页给出 8 个芯片同时读出一个 64 位字。本页回到一个芯片内部：读出的整行先复制到行缓冲，保留这一行使顺序访问的后续读取更快。
def memory_row(p):
    p.title("DRAM 内存模型下的访存模式")
    slide(p, r"""
- 内存读取一个字时，8 个 DRAM 芯片各自先读出所在的整行，锁存在芯片内部的**行缓冲**中。
""")
    p.frames(*(f"assets/memory-row-{k}.svg" for k in range(1, 6)), width_px=900)
    p.highlight("读出一整行的代价由行内的多次读取分摊")
    p.notes("""
DRAM 的一位由一个电容保存，读出时电容与位线连通，电荷被改变，所以读出是破坏性的。选中一行时，这一行的全部单元同时与各自的位线连通，由读出放大器把每一位放大并锁存，锁存的结果同时写回电容。这一整行的锁存器就是行缓冲。整行读出由 DRAM 的结构决定。
因此一次读取总是读出整行。不保留行缓冲时，每次读取之后这一行被关闭，下一次读取需要重新选中一行，这就是最简单的模型。保留行缓冲，对同一行的后续读取只需要从行缓冲取数据。
图中内存的一行是 4 个 8 字节的字，每个字存放 2 个 `int`，行缓冲是 8 个芯片的行缓冲合在一起，`w[0]` 至 `w[7]` 在行 0，`w[8]` 起在行 1。100 ns 与 10 ns 是示意值，实际芯片的行缓冲命中约十几纳秒，换行约几十到一百纳秒，随芯片与控制器而异。
`w` 与 `x` 位于不同的行。实际的芯片有多个存储体，每个存储体各有一个行缓冲，`w` 与 `x` 可以各用一个，所以图中只画 `w` 的读取。
第一帧是行与行缓冲。第二帧，读 `w[0]`，整行 `w[0]` 至 `w[7]` 读入行缓冲，100 ns。第三帧，读 `w[1]`，取自行缓冲，10 ns。第四帧，`w[2]` 至 `w[7]` 各 10 ns，8 次读取共 170 ns。第五帧，`w[8]` 在下一行，行缓冲被这一行替换，再用 100 ns。
""")


# 上一页的模型每次读取都需要 100 ns，几乎全部时间用于读内存。本页给出 DRAM 芯片里单元的二维排列，以及读一个超单元的两步，读出的是整行。
