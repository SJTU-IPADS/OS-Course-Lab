def locality(p):
    p.title("局部性原理")
    slide(p, r"""
- 程序倾向于引用最近引用过的数据，以及与它们地址相邻的数据，这个性质称为**局部性**。
- **时间局部性**：被引用过的一个存储位置，很可能在不久之后再次被引用。
- **空间局部性**：一个存储位置被引用之后，与它相邻的存储位置很可能在不久之后被引用。
""")
    figure(p, "locality", 900)
    slide(p, r"""
- 循环中的累加变量 `sum` 在每次迭代被引用，是时间局部性。数组 `w` 的元素按地址顺序被引用，是空间局部性。
""")
    p.notes("""
局部性是程序的性质。左图的横轴是时间，纵轴是地址，每个点是一次引用：同一个地址被引用八次，是时间局部性。八个相邻地址依次被引用，是空间局部性。
实际程序同时具有两种局部性：循环体里的变量与指令被反复使用，数组按下标顺序遍历。没有局部性的程序，例如按随机顺序访问一个很大的数组，两种局部性都没有。
""")


