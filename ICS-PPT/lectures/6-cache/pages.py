# 与上一部分的关系：上一部分以缓存的一般概念结束，其中区分了冷不命中、冲突不命中与容量不命中。
# 冲突不命中由放置策略造成，放置策略规定一个块放在缓存的哪些位置、如何找到它。本部分给出硬件上的放置策略。
# 回答：把地址拆成标记、组索引、块偏移三个字段。组索引选出一组，标记在组内选出一行，块偏移选出块内的字节。
# 三种模型（直接映射、组相联、全相联）只在每组有几行上不同。
# 页序：缓存在 CPU 与内存之间的位置 → 通用模型 (S, E, B) 与地址拆分 → E=1 的访问、示例、替换 →
# 冲突不命中暴露 E=1 的缺点（用 dot_product 的 w 与 x）→ 组索引取中间位 → E>1 的访问、示例、替换 →
# S=1 → 三种模型的对比 → 块长的测量方法与实测 → 练习。

# 上一部分给出缓存的一般概念。本页给出缓存在 CPU 与内存之间的位置，以及两侧的传输单位，
# 这两点使"由地址判断块是否在缓存中"成为硬件必须解决的问题。
def cache_between(p):
    p.title("CPU 与内存之间的缓存")
    slide(p, r"""
- CPU 用**地址**请求一个字（1 至 8 字节）。
- 缓存与内存之间以**块**为单位传输，块是内存中起始地址对齐、长度固定的一段连续字节。
- 缓存只保存内存的一部分块：请求的字所在的块在缓存中，缓存直接返回该字。块不在缓存中，缓存从内存取出整个块。
- 缓存接到地址后，必须判断这个地址所在的块是否在缓存中，并在缓存中找到它。
""")
    p.frames("assets/cache-between-1.svg", "assets/cache-between-2.svg",
             "assets/cache-between-3.svg", "assets/cache-between-4.svg",
             "assets/cache-between-5.svg", width_px=900)
    p.notes("""
CPU 的读写请求以字为单位，字长 1 至 8 字节。缓存与内存之间的传输以块为单位，一个块通常是 64 字节。
缓存的容量远小于内存，只能保存内存的一部分块。每次请求时，缓存只拿到一个地址，要用这个地址回答两个问题：它所在的块在不在缓存中，以及块在缓存的哪个位置。这两个问题由硬件在一次访问内完成，缓存模型就是为此设计的。
第一帧：CPU 把地址 A 交给缓存。
第二帧：情形一，A 所在的块在缓存中，缓存直接把 A 处的字返回给 CPU，内存不参与。
第三帧：情形二，A 所在的块不在缓存中，缓存把块的地址发给内存。
第四帧：内存返回整个块，缓存把它存入一行。
第五帧：缓存从这一行取出 A 处的字，返回给 CPU。
""")


# 上一页说明缓存要用地址找到块。本页给出缓存模型，使"找到"有一个确定的位置：组、行、块。
def cache_organization(p):
    p.title("缓存的组、行与块")
    with p.flex("row", valign="middle"):
        slide(p, r"""
- 缓存由 $S=2^s$ 个**组**构成，每组有 $E$ 行。
- 每行保存一个块的 $B=2^b$ 字节，另有 1 位**有效位**和 $t$ 位**标记**。
- 有效位为 1 表示该行保存着一个块。标记标识这个块在内存中的位置。
""")
        p.image("assets/cache-organization.svg", width_px=640, alt="缓存由 S 个组构成，每组 E 行，每行有有效位、标记和 B 字节的块；容量 C 等于 S、E、B 之积")
    slide(p, r"""
- 缓存的容量只计数据字节：$C=S\times E\times B$。
""")
    p.notes("""
图中的缓存是 $S=4$、$E=2$、$B=8$。
块是 $B$ 字节的数据，图中 $B=8$。块的字节在内存中是连续的一段。
一行由有效位、标记和一个块构成。有效位和标记是管理数据所需的额外存储。标记是地址中除去组索引和块偏移之后的高位部分，标识块在内存中的位置。
$E$ 行构成一组，图中 $E=2$。缓存由 $S$ 个组构成，图中 $S=4$。$S$ 与 $B$ 取 2 的幂，所以用 $s$ 位和 $b$ 位就能表示组号与块内字节号。
容量只计数据字节，$4\\times2\\times8=64$ 字节，有效位和标记不计入容量。
""")


# 上一页给出组、行、块。本页说明一个地址怎样对应到它们：地址的三个字段分别选出组、行与块内字节。
def cache_address(p):
    p.title("地址的标记、组索引与块偏移")
    slide(p, r"""
- $m$ 位的地址从高位到低位分为三个字段：$t$ 位**标记**，$s$ 位**组索引**，$b$ 位**块偏移**。
- **块偏移**选出块内的字节。**组索引**选出缓存中的组。**标记**在组内与各行的标记比较，选出行。
- 字段的位数由缓存的参数决定：$s=\log_2 S$，$b=\log_2 B$，$t=m-s-b$。
""")
    figure(p, "cache-address", 1120)
    p.notes("""
地址的拆分只取决于缓存的参数 $S$ 与 $B$。块偏移是地址的低 $b$ 位，同一个块内的 $B$ 个地址有相同的标记与组索引，只有块偏移不同。
组索引决定块放在哪个组，标记区分映射到同一个组的不同块。所以一个块的位置由组索引确定，块的身份由标记确定。
这一页的拆分对直接映射、组相联与全相联三种缓存模型都成立，三者的差别只是每个组里有几行。
""")


# 上一页给出地址的拆分。本页取 E=1，每组只有一行，选出组之后就确定了唯一的行，是最简单的模型。
def direct_mapped(p):
    p.title("直接映射缓存")
    with p.flex("row", valign="middle"):
        slide(p, r"""
- $E=1$ 的缓存是**直接映射缓存**：每组只有一行。
- 内存的每个块只能放入组索引所指的那一个组。
- 块 7 的起始地址是 $1110_2$，按 $t=1$、$s=2$、$b=1$ 拆分：块偏移为 $0$，组索引为 $11_2=3$，tag $=1$。
""")
        p.image("assets/direct-mapped.svg", width_px=680,
                alt="内存按地址空间画出 8 个块，每块两个字节，块 k 映射到组 k mod 4，块 0 与块 4 都映射到组 0")
    p.notes("""
块号等于地址除以 $B$。块号对 $S$ 取余得到组号，块号除以 $S$ 得到 tag，这与地址的两个字段对应。
图的左边按地址空间画出内存：一个块是相邻的两个方格，即块内的 $B=2$ 个字节，块左上角是块的起始地址，用 4 位二进制数表示，块号写在块的左边。内存有 8 个块，缓存有 4 个组，每组一行。块 0 至 3 依次映射到组 0 至 3，tag 都是 0。块 4 至 7 再次映射到组 0 至 3，tag 都是 1。
块 0 和块 4 的组号都是 0，tag 分别是 0 和 1，它们只能轮流占用组 0 的那一行。
以块 7 为例：起始地址 1110 按 $t=1$、$s=2$、$b=1$ 拆成 tag 1、组索引 11、块偏移 0，所以块 7 放入组 3 的那一行。
""")

def dm_access(p):
    p.title("直接映射缓存的访问步骤")
    slide(p, r"""
读取地址 13（二进制 1101），缓存 $t=1$、$s=2$、$b=1$：
1. **组选择**：用组索引选出一组。
2. **行匹配**：该行的有效位为 1 且标记等于地址的标记，则命中，否则不命中。
3. **字抽取**：命中时，用块偏移取出块内的字节。
""")
    p.frames("assets/dm-access-1.svg", "assets/dm-access-2.svg", "assets/dm-access-3.svg",
             width_px=980)
    p.notes("""
地址 13 的二进制是 1101，高 1 位是标记 1，中间 2 位 10 是组索引 2，低 1 位是块偏移 1。
第一帧用组索引 2 选出组 2。第二帧比较：组 2 的行有效位为 1，标记为 1，与地址的标记相等，命中。第三帧用块偏移 1 取出块内第 1 个字节，即 m[13]。
有效位为 0 或标记不等时都不命中，缓存要从内存取块。
""")


