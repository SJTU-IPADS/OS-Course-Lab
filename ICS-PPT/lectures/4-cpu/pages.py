def hazard(p):
    p.title('算术 data hazard')
    p.code('assembly', """imull   (%rdi,%r8,4), %ecx    # ecx = w[i] * x[i]
addl    %ecx, %r9d            # sum += w[i] * x[i]""")
    slide(p, r"""
`addl` 在译码阶段读 `%ecx`，`imull` 的乘积到写回阶段才写入 `%ecx`。流水线不做任何处理时，`addl` 在周期 3 读到的是 `%ecx` 的旧值，算出的和是错的。

 $$
 \mathit{sum} = \mathit{sum} + w_i \times x_i = 10 + 3 \times 4
 $$
""")
    figure(p, "hazard", 1120)
    p.notes("""
本页的流水线不做任何处理：两条指令相隔一个周期进入流水线，与「流水线时空图」一页的画法相同。imull 在第 3 周期的执行阶段算出乘积，经过第 4 周期的访存级，在第 5 周期写回；写入发生在第 5 周期结束的时钟沿，与「每个时钟周期执行一条指令」一页的「状态只在时钟沿写入」相同。addl 在第 3 周期译码，从寄存器堆读出 %ecx，这时 %ecx 中仍是 imull 之前的值。
图中两行之间是 %ecx 在各个周期的值。imull 之前的 movl (%rsi,%r8,4),%ecx 把 x[i] 读入 %ecx（第 3 讲的循环体），所以周期 1 至 5 都是 x[i] = 4，周期 5 结束的时钟沿变为 12。红色箭头是 addl 在周期 3 读到的值 4：addl 在周期 4 执行 10 + 4 = 14，在周期 6 把 14 写入 %r9d，正确的结果是 10 + 12 = 22。图上方的公式是这两条指令要算的和，w[i] = 3、x[i] = 4、sum = 10 只用来算出具体的数，读到旧值与取什么数无关。
后一条指令要读的寄存器，正是前一条指令要写、还没有写回的寄存器，这种情况就是本小节标题中的 data hazard。乘积在执行阶段算出，本页称为算术 data hazard；结果从内存读出的情况在本小节的「访存 data hazard」一页讲。
学生易错一：以为 imull 在第 3 周期算出乘积之后，%ecx 就已经是 12。乘积在第 3 周期结束时保存在执行级与访存级之间的级间寄存器中，%ecx 要到第 5 周期结束的时钟沿才写入。
学生易错二：以为只有紧挨着的两条指令才会读到旧值。imull 与 addl 之间隔一条或两条无关指令时，addl 在第 4 或第 5 周期译码，仍不晚于第 5 周期结束的写入，同样读到旧值；隔三条时 addl 在第 6 周期译码，才读到 12。
教学简化说明（供学生追问时解答）：带内存操作数的 imull (%rdi,%r8,4),%ecx 在五级流水线中按两条指令执行（先读出 w[i]，再做寄存器乘法），本小节「访存 data hazard」一页讲这一拆分；本小节前四页图中的 imull 一行是做乘法的那一条。
页末的问题：怎样让 addl 读到 imull 写回之后的 %ecx？
""")


def stall_bubble(p):
    p.title('stall 与 bubble')
    slide(p, r"""
最直接的办法：让 `addl` 停在译码级，等 `%ecx` 写回后再读。硬件对级间寄存器有两种操作：

- **stall**：时钟沿到来时，寄存器保持原内容，它后面一级的指令不变。
- **bubble**：时钟沿到来时，寄存器装入一条空指令，它后面一级不做任何操作。

只 stall 时，`addl` 的译码结果照常进入执行级，所以执行级同时插入 bubble。
""")
    figure(p, "stall-bubble", 1120)
    p.notes("""
问题来自上一页：addl 在第 3 周期译码时读到 %ecx 的旧值。要读到新值，addl 必须留在译码级，直到 imull 写回。
硬件让指令留在某一级，靠的是这一级前面的级间寄存器：每个时钟沿，级间寄存器装入前一级的输出，指令由此前进一级。stall 是让寄存器在这个时钟沿不装入、保持原内容，它后面那一级在下一个周期处理的仍是同一条指令。图中第二、三行，PC 与取指、译码之间的寄存器 stall：addl 留在译码级，addl $1,%eax 留在取指级，下一个周期再取一遍。
第二行是只 stall 的结果。译码级的电路在第 3 周期照常工作，把 addl 的译码结果（包括读到的旧值 4）送到译码与执行之间的寄存器；这个寄存器在时钟沿照常装入，addl 就有了两份：一份留在译码级，一份带着旧值进入执行级，继续向后推进，最后把错误的和写入 %r9d。stall 使 addl 留在译码级，译码级的输出仍然送往下一级。
第三行是 stall 与 bubble 同时使用的结果。bubble 让译码与执行之间的寄存器在这个时钟沿装入一条空指令（效果与 nop 相同），执行级在第 4 周期没有指令可做；这条空指令随后经过访存、写回，不改变寄存器与内存。stall 让 addl 留在译码级，bubble 占据 addl 原本要进入的执行级。访存级、写回级前面的寄存器照常装入，imull 照常前进到访存级。
一次 stall 只推迟一个周期。addl 在第 4 周期仍在译码级，%ecx 仍是旧值，硬件再 stall 一次、再插入一个 bubble，直到能读到写回后的值。
学生易错一：以为 stall 时整条流水线都停下。只有 PC 与取指、译码之间的寄存器保持原内容，执行、访存、写回各级照常前进，imull 照常走完。
学生易错二：以为 bubble 是程序里的一条 nop 指令。bubble 由硬件在运行时装入级间寄存器，程序的指令序列不变；它在流水线中的效果与 nop 相同。
本讲不讲判断何时 stall、何时插入 bubble 的控制电路（CS:APP 4.5.8 节的流水线控制逻辑）。
页末的问题：addl 要 stall 几个周期，才能读到 imull 写回之后的 %ecx？
""")


