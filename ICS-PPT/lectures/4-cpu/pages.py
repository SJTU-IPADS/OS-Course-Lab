LOOP = """movslq  %eax, %r8             # r8 = (long) i
movl    (%rsi,%r8,4), %ecx    # x[i]
imull   (%rdi,%r8,4), %ecx    # w[i] * x[i]
addl    %ecx, %r9d            # sum += w[i] * x[i]
addl    $1, %eax              # i++"""


