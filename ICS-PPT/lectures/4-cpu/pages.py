def forward_fig(p):
    p.title('data forwarding')
    slide(p, r"""
乘积在周期 3 执行结束时已经算出，存在执行级与访存级之间的级间寄存器中，只是写回之后才能从 `%ecx` 读到。

**转发**（data forwarding）：硬件把这个结果==直接送进下一条指令的执行阶段==。
""")
    p.frames("assets/forward-1.svg", "assets/forward-2.svg", "assets/forward-3.svg",
             "assets/forward-4.svg", "assets/forward-5.svg", width_px=1120)
    p.highlight("`addl` 直接使用从执行级转发而来的乘积\n寄存器 `%ecx` 在第 5 周期写回时才正式更新")
    p.notes("""
数据转发的核心思想：将前一条指令已经产生但尚未写回寄存器堆的运算结果，提前传送给后续需要使用该结果的指令。当 addl 进入执行级时，imull 已经离开执行级进入访存级；此时乘积结果正保存在执行级与访存级之间的级间寄存器中，硬件通过专用数据通路将其直接送入 addl 所在执行级的算术逻辑单元（ALU）输入端。教材 CS:APP 的 PIPE 模型将其画作送入译码级，无论画在译码出口还是执行入口，本质完全一致：省去等待写回的过程。本讲不展开转发控制电路的具体连线，只需明确该机制可消除此类等待。
这一页有 5 帧，每帧推进一个周期：第 2 帧（周期 3）imull 在执行阶段算出乘积；第 3 帧（周期 4）出现转发箭头，addl 进入执行；第 4 帧（周期 5）imull 写回 %ecx；第 5 帧 addl 走完五级，结论在这一帧出现。
图中的橙色折线箭头从 imull 的执行格（第 3 周期）指向 addl 的执行格（第 4 周期）：imull 在第 3 周期算出乘积，addl 在紧接着的第 4 周期进入执行级并直接使用转发过来的乘积。
与上一页对比：imull 的「写回」格位于第 5 周期，比 addl 的执行阶段晚一个周期，比乘积实际算出的时刻晚两个周期。等待写回时 addl stall 3 个周期、第 9 周期写回；转发消除了这 3 个周期的等待，addl 所在行的五个阶段紧密相连、没有「停」格，第 6 周期写回，不插入 bubble。代入「算术 data hazard」一页的数：addl 在第 4 周期拿到转发来的 12，算出 10 + 12 = 22，结果正确。
图中 imull 一行是拆分后做寄存器乘法的那一条（见「算术 data hazard」一页的讲稿），它的访存格与 addl 一样没有操作。
学生易错：将折线箭头误解为「在第 4 周期时寄存器 %ecx 已经被提前写入」。实际上第 4 周期内 %ecx 依然存放旧值，addl 获取的是来自级间寄存器的数据副本，%ecx 的正式更新仍发生于第 5 周期的写回阶段。
页末的问题：算术指令的结果在执行阶段末尾即已就绪，因此转发能够及时送达；但如果前一条指令的结果需要从内存中读取，转发还能赶上下一条指令的执行阶段吗？
""")


def load_use(p):
    p.title('访存 data hazard')
    p.code('assembly', """movl    (%rsi,%r8,4), %ecx    # ecx = x[i]
movl    (%rdi,%r8,4), %r10d   # r10d = w[i]
imull   %r10d, %ecx           # ecx = w[i] * x[i]""")
    slide(p, r"""
`x[i]`、`w[i]` 是数组 `x`（首地址在 `%rsi`）、`w`（首地址在 `%rdi`）的第 `i` 个元素。

冲突在 `%r10d`。有了转发，`imull` 仍然拿不到 `w[i]`：`movl` 在执行阶段只算出 `w[i]` 的地址，到访存阶段结束时才从内存读出 `w[i]`。
""")
    figure(p, "load-use", 1120)
    p.notes("""
拆分的依据：五个阶段中访存在执行之后，一条指令在执行阶段算出地址、在访存阶段读内存，读出的数据不再经过执行阶段。imull (%rdi,%r8,4),%ecx 要先读出 w[i] 再相乘，在五级流水线中只能按两条指令执行：一条 movl 读内存，一条 imull 做寄存器乘法。现代 x86 处理器核同样在译码时把它拆成「读内存」与「乘法」两步，读出的数据放在程序看不到的内部寄存器中；本页用循环体没有用到的 %r10d 代替这个内部寄存器（循环体用到 %eax、%ecx、%edx、%r8、%r9d、%rdi、%rsi）。
x[i] 与 w[i]：%r8 是符号扩展后的下标 i，(%rsi,%r8,4) 是 x 的首地址加 4i，即 x[i] 的地址（每个元素 4 字节）。第一条 movl 把 x[i] 读入 %ecx，第二条 movl 把 w[i] 读入 %r10d，imull 把两者相乘，乘积留在 %ecx。
冲突的位置：imull 读 %ecx 与 %r10d 两个寄存器。%r10d 由紧挨在前面的 movl 读出；%ecx 由再前一条 movl 读出，比 w[i] 早一个周期读出，imull 执行时 x[i] 已经可以转发。决定 imull 何时能执行的是 %r10d，因此图中只画 movl (%rdi,%r8,4),%r10d 与 imull 两行。
有了转发之后的时序：movl 在第 3 周期执行，算出的是 w[i] 的地址（%rdi 加 4i）；第 4 周期访存，w[i] 在第 4 周期结束时才从内存读出。imull 紧跟在 movl 后面，不 stall 时第 4 周期执行，执行一开始就需要 w[i]，这时 w[i] 还在读，硬件中没有可以转发的值。图中红色虚线框出第 4 周期一列，红色虚线箭头从 movl 访存格的末端指向 imull 执行格的开端，方向朝左，即指向更早的时刻，所以打叉。
与「data forwarding」一页对比：乘积在执行阶段末尾算出，下一条指令的执行在下一个周期，转发箭头朝右下；读内存的结果在访存阶段末尾才有，比乘积晚一级，与下一条指令的执行落在同一个周期。
学生易错一：以为冲突在 %ecx，即第一条 movl 读出的 x[i]。x[i] 与 imull 之间隔着一条指令，%ecx 比 %r10d 早一个周期读出；紧挨着的读内存与使用发生在 w[i] 上。
学生易错二：以为可以从 movl 的执行阶段转发。movl 的执行阶段算出的是地址，用这个地址访问内存之后才得到 w[i]。
页末的问题：imull 至少要推迟几个周期执行，才能用转发拿到 w[i]？用哪种操作让它推迟？
""")


def load_use_fig(p):
    p.title('stall 一个周期后转发')
    slide(p, r"""
`w[i]` 在周期 4 结束时才读出，`imull` 的执行要推迟到周期 5：`imull` 在译码级 ==stall 一个周期==，执行级在周期 4 插入一个 bubble；周期 5 硬件把 `w[i]` 转发进 `imull` 的执行阶段。图下方是当前周期五个阶段中的指令。
""")
    p.frames("assets/stall-1.svg", "assets/stall-2.svg", "assets/stall-3.svg",
             "assets/stall-4.svg", "assets/stall-5.svg", "assets/stall-6.svg", width_px=1120)
    p.notes("""
本页用「stall 与 bubble」一页的两种操作处理读内存后马上使用：第 3 周期 imull 在译码级，硬件发现它要读的 %r10d 由前一条 movl 从内存读出，第 3 周期结束的时钟沿，PC 与取指、译码之间的寄存器 stall，译码与执行之间的寄存器装入 bubble。第 4 周期 imull 仍在译码级，执行级是 bubble，movl 在访存级读出 w[i]，周期结束时存入访存级与写回级之间的级间寄存器；第 5 周期硬件把 w[i] 转发进 imull 的执行级，不等 movl 写回。stall 一次、插入一个 bubble 就够了，因为转发从访存级末尾取值，只比执行级末尾晚一级。本讲不讲判断何时 stall 的控制电路。
与「等待写回：stall 3 个周期」一页对比：那一页 stall 到写回之后，用 3 个周期；有了转发，读内存后马上使用只 stall 1 个周期。与「data forwarding」一页对比：算术指令的结果在执行阶段末尾产生，读内存的结果在访存阶段末尾产生，晚了一级，紧邻的下一条使用指令要 stall 一个周期。计算机体系结构教材将此类阻碍流水线连续推进的情况统称为 hazard，本页所示情形称为 load-use data hazard（读内存后马上使用）。
这一页有 6 帧，每帧推进一个周期（周期 2 至 7）。时空图下方与「等待写回：stall 3 个周期」一页相同，是周期号加粗的那个周期五个阶段中的指令，级间寄存器上方的 stall、bubble 是开始这个周期的时钟沿对它做的操作。第 2 帧（周期 3）imull 在译码级，要用 w[i]，movl 在执行级只算出 w[i] 的地址。第 3 帧（周期 4）movl 在访存，红框标出这一列；硬件图中 PC 与取指、译码之间的寄存器 stall，imull 留在译码级，执行级是 bubble，movl 在周期末读出 w[i]。第 4 帧（周期 5）出现转发箭头，寄存器照常装入，imull 进入执行级，用转发来的 w[i]，bubble 进入访存级。最后两帧两条指令走完五级，bubble 经过写回级后离开流水线。
图中标有「停」字的红色格子是 imull 在第 4 周期的状态：imull 留在译码级，执行级是 bubble。在红色虚线框出的第 4 周期这一列中，上方的 movl 正在访存，下方的 imull 在等 w[i]。绿色折线箭头从 movl 的访存格（第 4 周期）指向 imull 推迟后的执行格（第 5 周期）：访存阶段结束之后，读出的 w[i] 才能转发进入 imull 的执行阶段。多出的这一周期就是读内存后马上使用的代价。
将本图与「data forwarding」一页的时空图对比：两图中的转发箭头均从左上指向右下，颜色取数据来源阶段的颜色（那一页从执行发出，橙色；本图从访存发出，绿色）。区别在箭头的起点：那一页从第 3 周期的执行格发出，本图从第 4 周期的访存格发出；数据来源晚了一级，目标指令的执行格向右推移一列，中间是一个「停」格。上一页图中朝左的箭头，在本页变成朝右下的箭头。
stall 的这一周期内，排在 imull 后面的指令也随之推迟一个周期（图中未画出后续指令）。如果在 movl 与 imull 之间能够插入一条不依赖 %r10d 的无关指令（例如循环尾部的下标自增指令 addl $1,%eax），这一周期就用来执行这条指令，不需要 stall；编译器的指令调度优化正是利用这一原理重排指令顺序。
学生易错一：表述为「因为 %r10d 里还没有值所以要停」。准确的原因是此时 w[i] 尚未从内存读出，硬件中不存在可供转发的数据。学生易错二：误以为 stall 的周期内整个处理器都停止工作。movl 及其前面的指令照常向后推进，只有 imull 及其后面的指令推迟一个周期。
stall 一个周期是五级流水线模型假定「访存仅需一个周期」的推论。在真实处理器中，访问主存可能需要数十乃至上百个时钟周期，读内存后马上使用将导致更长时间的等待；访存延迟与缓存机制将在下一讲「存储层次」中详细讨论。
页末的问题：转发与 stall 解决的都是操作数尚未就绪的数据依赖。那么当遇到条件跳转指令 jl 时，取指部件在下一周期应当读取哪条指令？取指时能够知道跳转方向吗？
""")


def branch(p):
    p.title('control hazard')
    with p.flex("row"):
        p.code('assembly', """cmpl    %edx, %eax
jl      .L3
movl    %r9d, %eax    # not taken: return sum
ret""")
        p.code('assembly', """.L3:    # taken: loop body
movslq  %eax, %r8
movl    (%rsi,%r8,4), %ecx
imull   (%rdi,%r8,4), %ecx""")
    p.spacer(10)                       # a flex row drops the code blocks' bottom margin
    p.frames(*[f"assets/branch-wait-{k}.svg" for k in range(1, 5)], width_px=1120)
    p.highlight("每条 `jl` 都要多等 2 个周期：能不能不等？")
    p.notes("""
左边的代码是循环末尾的 cmpl、jl 与循环之后的两条指令，右边是跳转目标 .L3 处循环体的开头，都取自第 3 讲的汇编清单。cmpl 在执行阶段计算 i - n 并设置标志位；jl 在自己的执行阶段读标志位（cmpl 的标志位经转发送到），i < n 时跳回 .L3。jl 之后的「下一条指令」有两个候选：不跳时是顺序紧随其后的 movl %r9d,%eax，跳时是 .L3 处的 movslq %eax,%r8。
这一页有 4 帧。时空图只画 jl 与它的下一条两行；下方是周期号加粗的那个周期五个阶段中的指令，画法与 data hazard 各页相同。第 1 帧（周期 1）取进 jl。第 2 帧（周期 2）jl 在译码，取指级要取下一条，但 jl 还没有执行，不知道取哪一条：时空图上是灰色虚线的「?」格，硬件图的取指级也是「?」。第 3 帧（周期 3）jl 在执行，取指级仍不知道；周期 2 取进来的东西到了译码级，同样是「?」。橙色虚线标出周期 3 结束：jl 执行完，这时才知道跳不跳。
最后一帧是最简单的办法：等。jl 取进来之后，PC 在周期 1、2 结束的时钟沿 stall，取指级在周期 2、3 不取新指令（时空图中下一条的两个「停」格）；取指与译码之间的寄存器在周期 2、3 结束的时钟沿装入 bubble，译码级在周期 3、4 是 bubble。周期 3 结束时 jl 判定，PC 装入正确的地址，下一条在周期 4 取指。最后一帧的硬件图仍是周期 3：与第 3 帧相比，PC 标 stall，译码级的「?」换成了 bubble。这里 stall 与 bubble 的用法与「stall 与 bubble」一页相同：stall 让取指级停住，bubble 让它后面的译码级不做任何操作。
代价：每条 jl 之后都空出 2 个周期。本例循环体连同 cmpl、jl 共 7 条指令，每轮多等 2 个周期，执行时间增加近三成。
学生易错：以为下一条可以先按顺序取进来，等 jl 判定后再说。先按顺序取进来已经是在猜「不跳」；本页的做法是什么都不取，只等判定。
页末的问题：每条 jl 都要等 2 个周期。取指级能不能不等 jl 判定，先取一条进来？
""")


def branch_guess(p):
    p.title('分支预测：按猜测的方向取指')
    slide(p, r"""
等待判定时，每条 `jl` 之后多用 2 个周期。

**分支预测**：取指阶段不等待 `jl` 判定，==按猜测的方向接着取指==；等到 `jl` 执行完成之后，硬件核对猜测正确性。
""")
    p.columns(r"""
**猜对**
- 猜来的指令就是接下来要执行的指令
- 照常推进，不多用周期
""", r"""
**猜错**
- 猜来的指令全部==作废==
- 取指级从正确路径重新取指，多用的周期与等待判定相同
""", autobold=False)
    p.highlight("猜错时作废的指令，会不会已经改了寄存器或内存？")
    p.notes("""
上一页等待判定，每条 jl 之后多用 2 个周期。分支预测不等：取指级在 jl 判定之前就按猜测的方向取指，猜来的指令先进入流水线，与 jl 重叠执行；jl 在执行阶段结束时得出真实的方向，硬件拿它与猜测比较。
猜对时，猜来的指令就是程序接下来要执行的指令，流水线照常推进，等待的 2 个周期省下。猜错时，猜来的指令不该执行，全部作废，取指级改从正确路径取指；正确路径的第一条要到判定之后才取指，多用的周期与等待判定相同。所以在五级流水线中，按猜测取指不会比等待判定慢，猜对的比例越高，省下的周期越多。
猜什么：基础五级流水线可以用固定的策略，例如总是猜跳转（本例的 jl 在 n 轮循环中跳 n - 1 次，只在最后一次猜错），或总是猜不跳、顺序取下一条。按每条跳转指令以往的记录预测方向的硬件，在第三部分「硬件分支预测器」一页讲。
学生易错：以为猜测写在程序里，由程序员或编译器指定。猜测由取指级的硬件在运行时做，程序的指令不变。
页末的问题：猜错时要作废猜来的指令。这些指令在作废之前已经进入流水线，会不会已经改了寄存器或内存？先看猜对时它们在流水线中走到了哪里。
""")


