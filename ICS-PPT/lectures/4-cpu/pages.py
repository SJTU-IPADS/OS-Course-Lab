def stages(p):
    p.title('MiniCPU 指令的五个阶段')
    slide(p, r"""
每条指令==依次==经过五个阶段：

- **取指**：按程序计数器 PC 从内存读出一条指令；
- **译码**：识别指令的操作，从寄存器堆读出源操作数；
- **执行**：ALU 完成运算，或计算内存地址；
- **访存**：加载指令从内存读出数据，存储指令向内存写入数据；
- **写回**：把运算结果或读出的数据写入目的寄存器。

指令在用不到的阶段不做操作，如算术指令在访存阶段直接通过。
""")
    figure(p, "stages", 1120)
    p.notes("""
五级划分来自 MIPS 处理器：Hennessy 与 Patterson 的教材《计算机组成与设计》用它讲流水线，CS:APP 第 4 章 Y86-64 的流水线实现也分同样的五级。MIPS 指令定长，只有加载、存储指令访问内存，所以每条指令在五个阶段中各用一次，这个顺序对所有指令都适用。
按顺序说明各阶段的输入与输出：取指输入 PC，输出指令；译码输出指令的操作与源操作数；执行输出运算结果或内存地址；访存输出从内存读出的数据；写回把结果写入目的寄存器。源操作数在译码阶段集中读取，结果在写回阶段集中写入；第二部分「流水线执行的指令冲突」中的数据转发与流水线停顿均建立在这一时序前提之上。
并非所有指令都需要全部五个阶段的操作：算术指令在访存阶段无操作，存储指令在写回阶段无操作。硬件统一划分五个阶段，是为了让所有指令遵循相同的流水线结构。课堂提问：写内存的指令在哪一阶段无操作？答：写回阶段。
学生易错：把五级模型当成 x86-64 处理器的实际结构。五级模型是教学模型，实际处理器的级数更多，各级的分工也不同；本讲用它说明流水线的原理。
页末的问题：一条具体的指令依次经过五个阶段时，每个阶段用哪些硬件、做什么？
""")


def stage_units(p):
    p.title('五个阶段使用的硬件')
    slide(p, r"""
以指令 `movslq %eax, %r8` 为例，它的地址是 `0x20`，设 `%eax` = 5：
""")
    p.frames(*[f"assets/stage-units-{k}.svg" for k in range(1, 6)], width_px=1120)
    p.notes("""
图按 CS:APP 4.3 节 SEQ 的硬件图画：五个阶段自下而上排列，每个阶段一条横带；左侧的竖线把各阶段的输出向上传递，后面的阶段从中取用。每一帧点亮一个阶段用到的硬件，颜色与时空图的阶段配色相同，右侧写这一阶段对 movslq 做的事。
movslq %eax, %r8 的地址与字节取自第 3 讲 objdump -d dot.o（gcc -Og）：位于 0x20，长 3 字节，编码 4c 63 c0；%eax 是循环变量 i，这里取 5。逐帧讲：取指，PC 即第 3 讲的 %rip，指令内存按 PC = 0x20 读出 3 字节，PC + 指令长度得到 0x23，即下一条 movl 的地址（第 3 讲的 %rip ← %rip + 指令长度；MIPS 指令一律 4 字节，加的是 4）；译码，识别出这是 32 位到 64 位的符号扩展，读端口读出 %eax；执行，ALU 做符号扩展，5 的高 32 位补 0；访存，movslq 不访问内存，数据内存不工作，执行的结果沿左侧竖线直接到写回；写回，结果经顶部与右侧的通路送到写端口，写入 %r8。
寄存器堆是一块硬件，读端口与写端口分开，所以译码与写回各用一个端口。
执行一级的标志位保存 CF、ZF、SF、OF，算术与逻辑运算指令在执行阶段设置它们；movslq 不改变标志位，图中保持灰色。
跳转指令的下一条地址由执行阶段算出，图中只画 PC + 指令长度；跳转在第二部分 control hazard 一节讲。
学生易错：以为每条指令都要用到全部硬件。movslq 不用数据内存，存储指令不用寄存器堆的写端口；硬件按阶段齐备，一条指令只用其中的一部分。
页末的问题：五个阶段做完之后，0x23 什么时候写入 PC、%r8 什么时候变成新值，下一条指令什么时候开始？
""")


def clock_cycle(p):
    p.title('时钟周期')
    slide(p, r"""
**时钟周期**：相邻两个时钟沿之间的时间。PC、寄存器堆、标志位、数据内存只在时钟沿写入。
""")
    p.frames("assets/clock-1.svg", "assets/clock-2.svg", width_px=1120)
    p.notes("""
时钟是处理器内部周期变化的信号，写入发生在它的时钟沿（图中是上升沿），相邻两个时钟沿之间是一个时钟周期。第 3 讲测得的主频 3.8 GHz 即每秒 3.8 × 10^9 个时钟周期，一个周期约 0.26 纳秒。
PC、寄存器堆、标志位、数据内存保存处理器的状态，只在时钟沿写入；指令内存的读出、PC + 指令长度、ALU 这些部件不保存数据，输出随输入变化。
第一帧，周期 1 之内：PC 保持 0x20，movslq 的信号从取指依次传到写回，0x23 到达 PC 的输入，0x0000000000000005 到达写端口的输入；PC 与 %r8 仍是原来的值。
第二帧，周期 1 结束的时钟沿：PC 与 %r8 同时写入。周期 2 开始，指令内存按 PC = 0x23 读出下一条指令 movl (%rsi,%r8,4), %ecx（4 字节 42 8b 0c 86），它从取指开始。
学生易错：以为写回阶段一开始 %r8 就变成新值。周期之内写端口的输入已经就绪，%r8 到时钟沿才写入；在此之前读 %r8，得到的仍是原来的值。
页末的问题：处理器怎样一条接一条地执行指令？
""")


def insn_flow(p):
    p.title('指令流')
    slide(p, r"""
**指令流**：
1. 按 PC 从指令内存读出指令（取指）；
2. 依次经过译码、执行、访存、写回；
3. 时钟沿把下一条指令的地址写入 PC。
""")
    figure(p, "insn-flow", 1120)
    slide(p, r"""
处理器不断重复这三步，一条接一条地执行指令。顺序执行时，下一条指令的地址是 PC + 指令长度。
""")
    p.notes("""
本页对应旧讲义 ICS1 第 14 讲第 19 页「SEQ 硬件结构」：按 PC 读出指令、依次经过各阶段、更新 PC，处理器不断重复。这里按本讲的五级模型写：下一条指令的地址在取指阶段算出，周期结束的时钟沿把它写入 PC。原页的停机条件（halt、非法指令、非法地址）是 Y86 的规定，本页不讲。
图中三个框的编号与列表的三步对应：取指与四个阶段用时空图的阶段配色，时钟沿用深色粗框，与「时钟周期」一页的时钟沿相同；下方的箭头从时钟沿回到取指，开始下一条指令。
每个时钟周期走完一遍这三步，执行一条指令：「时钟周期」一页中，movslq 在周期 1 走完，movl 在周期 2 开始取指。
学生易错：以为取指之后 PC 马上指向下一条指令。取指阶段只算出下一条指令的地址，PC 在周期结束的时钟沿才写入。
页末的问题：一条算术运算指令在各阶段具体做什么？
""")


