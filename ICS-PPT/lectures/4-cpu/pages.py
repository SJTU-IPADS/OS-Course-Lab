def llm_spec_decode(p):
    p.title('投机解码')
    slide(p, r"""
- **草拟与验证**：**小模型**连续猜出 $k$ 个候选 token；**大模型**一次前向传播同时检验这 $k$ 个位置；
- **接受与作废**：从前往后逐位比对——猜对的全部接受；首个猜错位置改用大模型的 token，其后**全部丢弃**；
- **加速原理**：大模型读取一遍权重即可产出多个 token，提高受带宽限制的 decode 速率；
- **微架构对应**：与**分支预测及推测执行**同构——判定前按猜测路径先行推进，判定后作废猜错路径的后续部分。
""").footnote("投机解码：Yaniv Leviathan 等（Google），[Fast Inference from Transformers via Speculative Decoding](https://arxiv.org/abs/2211.17192)，ICML 2023；同期的 Charlie Chen 等（DeepMind），[Accelerating Large Language Model Decoding with Speculative Sampling](https://arxiv.org/abs/2302.01318)，2023")
    figure(p, "spec-decode", 1120)
    p.notes("""
常规 decode 阶段每读取一遍庞大的模型权重仅能产出 1 个 token，显存带宽严格限制了单请求的生成速度。投机解码（Speculative Decoding）引入一个体量小一到两个数量级的草稿模型（Draft Model）：先由草稿模型以极低开销快速自回归生成 k 个候选 token，随后将这 k 个候选 token 拼成序列送入目标大模型（Target Model），执行一次并行前向计算。由于同时输入了 k 个 token，大模型这一步执行的是高算术强度的矩阵乘矩阵运算（与 prefill 相同），在读取一遍权重的时间内即可同时算出全部 k 个位置对应的正确输出分布。接着从左向右逐位核对：若草稿模型在某位置猜中了大模型的选择，则直接接受；一旦在某个位置首次出现偏差，则将该位置替换为大模型算出的正确 token，并将草稿模型在此位置之后基于错误前提继续猜出的候选 token 全部作废丢弃。
观察配图（取草拟步长 k = 4）：草稿模型猜出 4 个候选词，经大模型一次前向并行验证，前两个位置猜对并予以保留，第三个位置猜测错误，直接采用大模型在该位置生成的正确词 t3′，第四个候选词由于建立在错误的第三个词之上而被直接作废。在这一轮中，目标大模型仅读取一遍权重便净产出了 3 个有效 token（即便第一个位置就猜错，也能保底产出大模型自身算出的第 1 个正确 token），从而成倍缩短了单请求的生成时间。
与前文「control hazard 与分支预测」及「现代处理器核的三项扩展」对照：条件跳转指令 jl 要到执行阶段才能确定方向，处理器的分支预测器在判定前按预测方向提前取指并推测执行，一旦发现猜错便将错误路径上的后续指令全部作废；投机解码同样按草稿模型的预测先行向后展开，再由大模型一次性完成判定，并将猜错位置之后的候选全部丢弃。更为关键的是，两套机制的最终语义都严格由「验证方」决定：处理器的最终架构状态严格遵循指令集（ISA）顺序语义，推测执行绝不改变程序结果；投机解码经验证修正后的输出序列，在数学分布上与目标大模型逐个 token 慢速生成的输出完全等价，绝不因引入小模型而损失生成质量。
草稿模型自身的参数量极小，其连续猜测 k 步的耗时远小于大模型一次前向传播，因此即便猜测错误，额外付出的时间代价也十分有限；实际加速比取决于草稿模型对大模型的拟合准确度以及文本本身的可预测性。
页末的问题：将本讲前半部分的处理器微架构与后半部分的推理服务放在一起，二者在系统结构上呈现出怎样的对应关系？
""")


