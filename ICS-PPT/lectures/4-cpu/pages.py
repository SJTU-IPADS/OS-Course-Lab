def ooo_inorder(p):
    p.title('乱序执行：如果读内存要 3 个时钟周期')
    p.code('assembly', """movl    (%rdi,%r8,4), %r10d   # r10d = w[i]
imull   %r10d, %ecx           # ecx = w[i] * x[i]
addl    %ecx, %r9d            # sum += w[i] * x[i]
addl    $1, %eax              # i++
cmpl    %edx, %eax            # compare i with n""")
    p.frames(*[f"assets/ooo-inorder-{k}.svg" for k in range(1, 5)], width_px=1080)
    p.notes("""
五条指令取自「访存 data hazard」一页拆分后的循环体：movl (%rdi,%r8,4),%r10d 读出 w[i]，imull %r10d,%ecx 相乘，addl %ecx,%r9d 累加，addl $1,%eax 把 i 加 1，cmpl %edx,%eax 比较 i 与 n。页面上是这五条指令的汇编，图中的行标签只写到能区分各条指令为止。
图上的假设（标题中的「读内存要 3 个周期」）：读 w[i] 要 3 个周期，movl 的访存格画成 3 格宽。五级模型假定访存只占 1 个周期；真实处理器读内存常要多个周期，访问主存要几十到上百个周期（下一讲「存储层次」）。图从周期 3 画起，movl 的取指、译码在周期 1、2。
本部分的处理器把译码后、还不能执行的指令保存在内部，取指与译码照常进行，每个周期取进、译码一条新指令；图中的红色「停」格表示译码后的指令在等待执行。本页的执行顺序是程序顺序：一条指令要等它前面的指令都执行之后才执行。
逐行看：imull 在周期 3 译码，w[i] 到周期 6 结束才读出，周期 4 至 6 等待，周期 7 用转发来的 w[i] 执行，与「stall 一个周期后转发」一页相同。addl %ecx,%r9d 在周期 4 译码，要等乘积，周期 8 用转发来的乘积执行。addl $1,%eax 在周期 5 译码，操作数 %eax 已就绪，按程序顺序要排在 addl %ecx,%r9d 之后，等到周期 9 执行。cmpl 在周期 6 译码，排在 addl $1,%eax 之后，周期 10 用转发来的新 %eax 执行、周期 12 写回。
这一页有 4 帧：第 1 帧是周期 3；第 2 帧是周期 4 至 6，w[i] 还在读，后面的指令照常取指、译码，然后等待；第 3 帧是周期 7，w[i] 读出，绿色折线把它送进 imull 的执行阶段；第 4 帧是周期 8 至 12，橙色折线把乘积送进 addl %ecx,%r9d 的执行阶段，另一条橙色折线把 addl $1,%eax 在周期 9 算出的新 %eax 送进 cmpl 的执行阶段，五条指令在周期 7、9、10、11、12 写回。最后一帧图顶的一行字换成本页的问题：页面上有代码块，图下方放不下 highlight。
与第二部分的区别：「stall 一个周期后转发」一页的五级流水线让等待的指令留在译码级，后面的指令 stall 在取指级；本部分的处理器在译码之后保存等待的指令，后面的指令照常译码。执行仍按程序顺序时，两种做法中 addl $1,%eax 都在周期 9 执行。
学生易错：以为 imull 等待只推迟 imull 一条指令。按程序顺序执行时，排在 imull 后面的每条指令都随之推迟：imull 不必等待时，后四条指令依次在周期 4 至 7 执行，addl $1,%eax 在周期 6 执行，现在推迟到周期 9。
页末的问题（最后一帧图顶）：周期 4 至 6，流水线的五级各在做什么，哪些硬件在工作？
""")


