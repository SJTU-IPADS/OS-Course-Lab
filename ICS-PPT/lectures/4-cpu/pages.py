def ooo_independent(p):
    p.title('乱序执行：指令的相关性')
    p.table(headers=["指令", "读的寄存器", "写的寄存器", "用到前面哪条的结果"],
            rows=[["`movl (%rdi,%r8,4), %r10d`", "`%rdi`、`%r8`", "`%r10d`", "无"],
                  ["`imull %r10d, %ecx`", "`%r10d`、`%ecx`", "`%ecx`", "`movl` 读出的 `w[i]`"],
                  ["`addl %ecx, %r9d`", "`%ecx`、`%r9d`", "`%r9d`", "`imull` 的乘积"],
                  ["`addl $1, %eax`", "`%eax`", "`%eax`", "无"],
                  ["`cmpl %edx, %eax`", "`%edx`、`%eax`", "标志位", "`addl $1,%eax` 的结果"]])
    slide(p, r"""
`addl $1,%eax` 只读写 `%eax`，前三条指令都不写 `%eax`：它在周期 5 译码时操作数已就绪，周期 6 至 8 等待，只因为按程序顺序要排在 `imull` 与 `addl %ecx,%r9d` 后面。先执行它，`%eax` 得到的值相同；用到它结果的 `cmpl` 也能随之提前。

**乱序执行**：译码后的指令在==操作数就绪时执行==，后面的无关指令可以先于等待中的指令执行；结果仍==按程序顺序写回==寄存器，不早于前面的指令，可以与前一条在同一个周期写回；同一个周期最多写回几条由硬件结构决定，这里设为两条（即假定寄存器堆有两个写端口）。
""")
    p.notes("""
判断两条指令是否有关看寄存器：后一条要读的寄存器若是前一条要写的寄存器，后一条就要等前一条的结果，这是第二部分 data hazard 的依赖；否则两条无关。表中逐条列出五条指令读、写的寄存器：movl 写 %r10d，imull 读 %r10d、写 %ecx，addl %ecx,%r9d 读 %ecx，前三条是一条依赖链；addl $1,%eax 读写的 %eax 不是前三条写的寄存器，前三条也不读 %eax，它与前三条无关；cmpl 读 addl $1,%eax 写的 %eax，要等它的结果。movl 读的 %rdi、%r8，imull 读的 %ecx，cmpl 读的 %edx 由更早的指令写入（%r8 来自 movslq，%ecx 来自 movl (%rsi,%r8,4),%ecx，%edx 是参数 n），在周期 3 之前已经就绪。
addl $1,%eax 的操作数 %eax 由上一轮的 addl $1,%eax 写入，早已就绪。前两页中它周期 9 才执行，原因只是按程序顺序执行时它排在 imull 与 addl %ecx,%r9d 后面；在周期 6 执行它，读到的 %eax 与周期 9 读到的相同，算出的 i + 1 也相同。
乱序执行的两条规则：执行部件在每个周期从译码后等待的指令中挑一条操作数已经就绪的执行，有多条就绪时先执行程序顺序靠前的；写回按程序顺序，一条指令不早于它前面的指令写回，可以与前一条在同一个周期写回。
「可以与前一条在同一个周期写回」：按程序顺序只要求一条指令不早于它前面的指令写回。真实处理器每个周期可以按程序顺序写回多条：Intel Skylake 每个周期最多 4 个操作，AMD Zen 5 每个周期最多 8 项（两家的优化手册）。教材把这一步称为提交（commit）或退休（retire）：结果算出后先存在处理器内部，提交时才按程序顺序写入程序看到的寄存器；本讲的「写回」指写入程序看到的寄存器这一步。本部分的处理器每个周期只取指、译码、执行一条，写回设为每个周期最多两条，寄存器堆要有两个写端口。
写回按程序顺序的原因：程序看到的是寄存器与内存的变化，写回按程序顺序，这些变化的先后与按程序顺序执行完全相同。先算出的结果在写回之前只在处理器内部，与「data forwarding」一页中尚未写回的乘积相同；后面要用它的指令（这里的 cmpl）从处理器内部取得。
与「stall 一个周期后转发」一页的讲稿对照：那里提到编译器可以把 addl $1,%eax 挪到 movl 与 imull 之间，在编译时重排指令；乱序执行由硬件在运行时做同样的重排，程序的指令序列不变。
学生易错：以为相邻的指令一定有关。是否有关只看寄存器：addl $1,%eax 紧跟在 addl %ecx,%r9d 后面，仍与前三条无关；两条指令相隔再远，后一条读的是前一条要写的寄存器，就要等。
页末的问题：按这两条规则，addl $1,%eax 与 cmpl 在哪个周期执行，五条指令在哪个周期全部写回？
""")


