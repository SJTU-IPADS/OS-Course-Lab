"""ICS 第 4 章：指令如何在 CPU 中重叠执行。

页面函数的顺序与 lecture.py 中页面的顺序相同。
配图由 diagrams/ 下的脚本生成。粗体在文案里逐处写明，slide() 关闭自动加粗。
例子是第 3 讲 gcc -Og 编译的 dot_product 循环体，不另设一套指令集。
"""


def slide(p, md, **kw):
    return p.slide(md, autobold=False, **kw)


def figure(p, name, width):
    return p.image(f"assets/{name}.svg", width_px=width)


LOOP = """movslq  %eax, %r8
movl    (%rsi,%r8,4), %ecx    # x[i]
imull   (%rdi,%r8,4), %ecx    # w[i] * x[i]
addl    %ecx, %r9d            # sum += ...
addl    $1, %eax              # i++"""


def question(p):
    p.title('第 3 讲留下的问题')
    slide(p, r"""
**第 3 讲已经做完的**：`dot_product` 被编译成一串 x86-64 指令；实测里，运算单元的峰值填不满，因为每个权重都要从内存读一次。

**这一讲的问题**：这些指令在 CPU 里是一条做完再做下一条，还是几条同时在做？
""")
    p.notes("""
答案在第二部分：几条指令同时在做，各自处在不同的阶段。本讲先把一条指令拆成五个阶段，再说明阶段可以重叠、重叠时会停，最后说明现代核在这五级之上还做乱序与预测。流水线填的是运算单元，解释不了第 3 讲测到的带宽墙；存储层次是下一讲。
""")


def loop_body(p):
    p.title('仍用第 3 讲的循环体')
    p.code('assembly', LOOP)
    slide(p, r"""
`%eax` 是 `i`，`%r9d` 是 `sum`，`%rdi` 与 `%rsi` 是 `w` 与 `x`。下面用第二条指令走完五个阶段：`movl (%rsi,%r8,4), %ecx`，它读出 `x[i]`。
""")
    p.notes("""
清单是第 3 讲 gcc -Og -fcf-protection=none 编译 dot.c 的循环体，去掉了标号。%r8 是 movslq 把 i 扩展成的 64 位下标。
""")


def stages(p):
    p.title('一条指令的五个阶段')
    slide(p, r"""
`movl (%rsi,%r8,4), %ecx` 这一条里，五件事依次发生：

- **取指**：按 `%rip` 从内存读出这条指令的字节；
- **译码**：认出这是 `movl`，基址在 `%rsi`，变址在 `%r8`，目的在 `%ecx`；
- **执行**：算出地址 `%rsi + %r8 * 4`；
- **访存**：从该地址读出 4 字节的 `x[i]`；
- **写回**：把读出的值写入 `%ecx`。
""")
    p.notes("""
五个名字都落在第 3 讲已经读过的这条指令上。加法指令的访存阶段无事可做，store 指令的写回阶段无事可做；阶段的名字按会做全五件事的那类指令来起。
""")


def stages_fig(p):
    p.title('一条指令的五个阶段')
    figure(p, "stages", 1120)
    slide(p, r"""
**单周期实现**：这五步串在同一个时钟里。时钟必须长到五步都能做完，下一条指令才能开始。
""")
    p.notes("""
单周期实现功能正确，时钟被最慢的那条指令拖着走。访存比一次加法慢，加法指令也要等满这个时钟。
""")


def pipeline(p):
    p.title('流水线改变的是吞吐，不是一条指令的延迟')
    slide(p, r"""
- **五个阶段同时工作**：第一条在写回时，第二条在访存，第三条在执行，第四条在译码，第五条在取指；
- **吞吐**：每个时钟可以完成一条指令的一个阶段，理想情况下每个时钟做完一条指令；
- **延迟**：一条指令仍要走完五级。级与级之间还要插入寄存器，一条指令花的时间比单周期更长。
""")
    p.notes("""
流水线提高的是单位时间完成的指令数。学生容易以为每条指令都变快了；单条指令因为多了级间寄存器，从进入到写回的时间变长。
""")


def pipeline_fig(p):
    p.title('循环体的五条指令重叠执行')
    figure(p, "pipeline", 1120)
    p.notes("""
图的五行是上一页之前列出的循环体，自上而下按程序顺序。每一格是该指令在该周期所处的阶段。周期 5 时五级同时有指令：movslq 在写回，movl 在访存，imull 在执行，第一条 addl 在译码，addl $1 在取指。从这一拍起，每个周期都有一条指令写回。
""")


def pipe_limit(p):
    p.title('时钟由最慢的一段决定')
    figure(p, "pipe-limit", 1120)
    slide(p, r"""
- **段不均匀**：三段里有一段特别慢时，时钟等于这一段的时间，另外两段做完后空等；
- **段间寄存器**：每加一级就多一次保存。级数变多，寄存器占去的时间比例变大。
""")
    p.notes("""
左图是三段工作量不同的示意，中间一段决定时钟，对应书上第 4.4 节用来说明限制的算术流水线，不是一台要去实现的处理器。右图的小方块是级与级之间的寄存器。这两点说明五级流水线的时钟不是单周期时钟的五分之一。
""")


def forward(p):
    p.title('结果刚算出来，下一条就可以用')
    p.code('assembly', """imull   (%rdi,%r8,4), %ecx
addl    %ecx, %r9d""")
    slide(p, r"""
`imull` 在执行阶段算出乘积，写入 `%ecx` 的正式写回还在两级之后。`addl` 的执行阶段需要这个乘积时，乘积已经算完，可以从执行阶段直接送过去，不必等写回。
""")
    p.notes("""
这种把结果提前送给后面指令的做法叫转发。addl 进入执行的那个周期，imull 已经离开执行、处在访存；要转发的值是上一拍执行阶段算出的乘积。这里不画转发的电路，只确定这件事办得到、addl 不用停。
""")


def forward_fig(p):
    p.title('结果刚算出来，下一条就可以用')
    figure(p, "forward", 1120)
    p.notes("""
箭头从 imull 的执行格指向 addl 的执行格。两格不在同一拍：imull 先执行，addl 下一拍执行，用的是转发来的 %ecx。
""")


def load_use(p):
    p.title('读内存的结果，下一条马上要用')
    p.code('assembly', """movl    (%rsi,%r8,4), %ecx
imull   (%rdi,%r8,4), %ecx""")
    slide(p, r"""
`movl` 要到访存阶段结束才拿到 `x[i]`。紧接着的 `imull` 若按节拍进入执行，访存还没结束，`%ecx` 里还没有这个值。转发来不及，`imull` 在译码和执行之间停一拍。
""")
    p.notes("""
停顿发生在访存与执行之间：停的那一拍，movl 在访存，imull 还不能进入执行。下一拍访存结束，值可以送进 imull 的执行。只讲这一拍，不讲停顿控制电路。
""")


def load_use_fig(p):
    p.title('读内存的结果，下一条马上要用')
    figure(p, "stall", 1120)
    p.notes("""
图中标「停」的那一格原来应是 imull 的执行。同一列上 movl 标的是访存。多出来的这一拍就是 load 的结果立即被使用时的代价。
""")


def branch(p):
    p.title('分支还没算出来，下一条已经被取进来')
    p.code('assembly', """cmpl    %edx, %eax
jl      .L3""")
    slide(p, r"""
`jl` 是否跳转，要到执行阶段比较完 `i` 与 `n` 才知道。取指阶段每个时钟都在取指令，此时下一条已经取进来了。猜错时，这些指令作废。
""")
    p.notes("""
循环末尾的 jl .L3 来自第 3 讲的同一份清单：i < n 时跳回循环体。取指不能等执行阶段的结果，否则流水线的第一级就停了。猜对哪一边是下一节的事；这一页只建立「取的时候还不知道」这件事。
""")


def branch_fig(p):
    p.title('分支还没算出来，下一条已经被取进来')
    figure(p, "branch", 1120)
    p.notes("""
jl 处在执行阶段时，下一条已经过了取指。虚线框是猜错后作废的那条。作废的指令不写寄存器、不写内存。
""")


def modern(p):
    p.title('现代的核在这五级之上还做三件事')
    slide(p, r"""
- **乱序执行**：操作数已经准备好的指令先做，不必等它前面的指令做完；
- **分支预测与推测执行**：先按预测的方向取指令并往下做，猜错就把这些结果作废；
- **一个周期发射多条指令**：同一拍可以有多条指令进入执行，完成的指令数可以多于周期数。
""")
    p.notes("""
三件事都是微架构，不改变第 3 讲讲的指令集：程序仍按 ISA 规定的顺序看见结果。乱序与推测执行必须把结果按程序顺序提交，猜错或发生异常时已经推测的结果不能露出去。一个周期发射多条指令时，IPC（每周期完成的指令数）可以大于 1。
""")


def bandwidth(p):
    p.title('流水线填的是运算单元')
    slide(p, r"""
- **IPC 可以大于 1**，也会因为预测失败、以及访存停顿，远低于运算单元的峰值；
- **第 3 讲的矩阵乘向量**：每个权重参加一次乘加，并从内存读一次。流水线让乘加重叠，不减少这次读取；
- **带宽墙还在**：生成一个 Token 要读的权重字节数没变，速度的上限仍是内存带宽除以这些字节。
""")
    p.notes("""
第 3 讲的结论：单请求自回归推理处于访存受限区。这一讲说明 CPU 内部可以把多条指令重叠、一个周期做多条，这提高的是运算吞吐。权重仍是每个读一次，字节数不变，所以填满流水线也到不了第 3 讲算出的算术峰值。
""")


