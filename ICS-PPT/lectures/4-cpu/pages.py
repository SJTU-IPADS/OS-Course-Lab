def stage_hardware(p):
    p.title('流水线原理')
    slide(p, r"""
- **阶段按硬件划分**：五个阶段各由一组独立的硬件负责，图中每一行是一组硬件；
- **单周期实现中**：一条指令在某一阶段时，只有该阶段的硬件在工作，其余四组==空闲==。
""")
    figure(p, "stage-hw", 1120)
    slide(p, r"""
**解决方案**：相邻两级之间加入==级间寄存器==保存本级结果，每组硬件在下一个周期即可处理下一条指令，五组硬件同时处理五条指令，时钟周期只需容纳一个阶段，这种执行方式称为==流水线==。
""")
    p.notes("""
五个阶段的划分依据是硬件，与洗车通道的每一段只做一步相同：取指用指令内存读出指令字节，译码读寄存器堆，执行用 ALU，访存读写数据内存，写回写寄存器堆。图中每一行是一组硬件，色块是它为某条指令工作的时间，空白是它空闲的时间；阶段宽度与「每个时钟周期执行一条指令」一页的图相同，只展示 movl 的一个周期。
取指与访存都访问内存，在硬件上是两条独立的访问通路，CS:APP 的 SEQ 把它们画成指令内存与数据内存两块；寄存器堆的读端口与写端口也是分开的，同一个周期里可以一读一写。
引导学生观察配图：movl 访存时只有数据内存在工作，其余四行都是空白。每一行在一个周期里只有一小段在工作。
学生易错：以为五个阶段共用同一块电路，只能依次进行。五个阶段用的是五组不同的硬件，所以它们可以同时为不同的指令工作。
解决方案一段：流水线让每组硬件在每个周期都为一条指令工作，做到这一点要靠级间寄存器。单周期实现的阶段之间不保存结果，一条指令的中间结果只能在一个周期内一路传到写回；在相邻两级之间加上寄存器后，时钟沿把每一级的结果存入，下一级在下一个周期读取，这一级的硬件随即开始处理下一条指令。时钟周期因此只需容纳一个阶段，再加上寄存器的时间。每个时钟周期各指令同步向后推进一级：第 1 条指令处于写回级时，第 2 至第 5 条分别处于访存、执行、译码与取指级。
页末的问题：执行循环体的 5 条指令，单周期实现与五级流水线各自需要多少个时钟周期？
""")


