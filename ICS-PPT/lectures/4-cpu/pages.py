def video_pipeline(p):
    p.title('视频播放流水线')
    slide(p, r"""
- 播放器将视频分成若干小段，每段依次经过：**下载**（从网络获取压缩数据）→ **解码**（还原为逐帧画面）→ **显示**（屏幕每 16.7 ms 刷新一帧）。
- 三级同时工作：屏幕显示第 1 段时，解码器还原第 2 段，网络下载第 3 段；相邻两级之间是缓冲区。播放开始前的「缓冲」过程即流水线的进管。
- 显示的节拍固定；网络速度低于播放速度时，缓冲区被读空，画面停止，即 ==bubble==。播放器自动降低清晰度，减少的是==最慢一级==的工作量。
""")
    figure(p, "video-pipeline", 1120)
    p.notes("""
视频网站将一部视频分成每段几秒（HLS、DASH 等协议均如此），播放器按段下载。下载的数据是压缩格式，须解码为逐帧画面；屏幕按固定节拍刷新，60 Hz 的屏幕每 16.7 ms 一帧。三级分别由网卡、解码器（CPU 或专用硬件）与显示硬件完成，级间由缓冲区衔接，作用与级间寄存器相同：前一级写入结果，后一级从中读取。
与本讲逐项对照。进管：打开视频后先显示加载图标再开始播放，这段时间在填充前两级，缓冲区积累几秒画面后显示才开始，对应流水线最初几个周期后面的级尚未收到数据。节拍：显示一级的节拍固定，作用相当于时钟；下载一级的速度随网络变化。bubble：网络变慢时，「已解码、未显示」的缓冲区被显示读空，下一帧无法显示，画面停止并显示加载图标，对应时空图上的 bubble 格。降低清晰度：播放器检测到反复卡顿后切换到较低清晰度，每段的数据量减小，最慢的一级（下载）能够跟上显示的节拍，对应「时钟周期由最长的阶段决定」一页：缩短最慢一级的时间，整条流水线的吞吐才能提高。
与级间寄存器的区别：级间寄存器只保存一级一个周期的结果，视频的缓冲区可保存几秒的数据，能够吸收网络速度的波动；缓冲越多，越不容易卡顿，但打开视频后的等待时间越长（延迟增加）。这同样是吞吐与延迟之间的权衡。
学生易错：以为「缓冲」是下载整部视频。缓冲区只保存接下来几秒的数据，下载与播放同时进行，因此几小时的电影也能在几秒内开始播放。
页末的问题：本讲出现的几条流水线有哪些共同的设计？
""")


