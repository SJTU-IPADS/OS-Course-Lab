def video_pipeline(p):
    p.title('看视频：下载、解码、显示')
    slide(p, r"""
- 播放器把视频切成一小段一小段。每一段依次经过：**下载**（从网络取压缩数据）→ **解码**（还原成一帧帧画面）→ **显示**（屏幕每 16.7 ms 换一帧）。
- 三步同时进行：屏幕在放第 1 段时，解码器在还原第 2 段，网络在下载第 3 段；段与段之间是缓冲区。开始播放前先「缓冲几秒」，就是把流水线填满（进管）。
- 显示的节拍固定；网络慢于播放，缓冲区读空，画面停住转圈：这就是==气泡==。播放器自动降低清晰度，是在给==最慢的一级==减负。
""")
    figure(p, "video-pipeline", 1120)
    p.notes("""
每个人都见过的流水线。视频网站把一部视频切成几秒一段（HLS、DASH 等协议都这样做），播放器按段下载。一段数据下载完是压缩格式，要解码成一帧帧画面；屏幕以固定节拍换帧，60 Hz 的屏幕每 16.7 ms 一帧。三步分别由网卡、解码器（CPU 或专用硬件）和显示硬件负责，中间用缓冲区衔接，和级间寄存器一样：前一级把结果放进去，后一级从里面取。
逐条对照本讲。进管：点开视频时先转一下圈再开始放，是在把前两级填上，等缓冲区里有了几秒的画面才让显示开始，对应流水线前几拍后面的级还没拿到数据。节拍：显示这一级的节拍是固定的，相当于时钟；下载这一级的速度随网络变化。气泡：网络一慢，「已解码、未显示」的缓冲区被显示取空，下一帧没有，画面停住转圈，这正是时空图上的停格。减负：播放器发现反复卡顿，就自动切到更低清晰度，每段的数据量变小，最慢的一级（下载）跟得上了，对应第 10 页「周期由最慢的一级决定」——缩短最慢一级的时间，整条流水线才快得起来。
与级间寄存器的一点不同：级间寄存器只保存一级的一拍结果，这里的缓冲区存着好几秒的数据，所以能吸收网络速度的忽快忽慢；缓冲得越多，越不容易卡，但点开后要等得越久（延迟变长）。这又是吞吐与延迟的取舍。
学生易错：以为「缓冲」是在下载整部视频。缓冲区里只有接下来几秒的数据，边下边放，所以几个小时的电影也能几秒内开始播。
页末的问题：把本讲出现过的几条流水线放在一起，它们共用哪些设计？
""")


