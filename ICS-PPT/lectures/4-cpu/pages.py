def smt_hw(p):
    p.title('超线程：硬件结构设计')
    slide(p, r"""
**超线程**：一个核心同时运行两个线程。==PC 与寄存器堆各有两份==，每个线程一份，保存这个线程执行到哪一条、各寄存器的值；取指、译码、执行部件、访存、写回的硬件==由两个线程共用==。
""")
    figure(p, "smt-hw", 1120)
    p.notes("""
第 3 讲「线程并行：CPU 多核与 GPU」一页讲过：每个线程有自己的 %rip，各自取指、执行。一个线程在核心中的状态是它的 PC 与寄存器：PC 记录执行到哪一条，寄存器保存它的数据。超线程把这两样各复制一份，一个核心同时保存两个线程的状态；其余硬件只有一份，两个线程共用。
图分三条。上方蓝色是线程 A 的 PC 与寄存器堆，下方橙色是线程 B 的；两个寄存器堆有同样的寄存器名（%rax 至 %r10 与其余寄存器），各存各的值。中间是两个线程共用的硬件，即「超标量」与乱序执行几页的核心：取指，译码，译码后等待执行的指令，两个执行部件，访存（结果已算出、等待写回的指令在它下方的虚线框中），写回。取指按 PC A 或 PC B 取指令；译码读、写回写的都是这条指令所属线程的寄存器堆。框中的灰字说明这一级怎样对待两个线程，下一页逐条讲。
两个线程执行同一段代码时，例如两个线程各对矩阵的一行调用 dot_product，两条 addl $1,%eax 写的是两个不同的 %eax：线程 A 的 %eax 是 A 的 i，线程 B 的 %eax 是 B 的 i。
Intel 的第一个实现（Marr 等，Hyper-Threading Technology Architecture and Microarchitecture，Intel Technology Journal 第 6 卷第 1 期，2002，Xeon 处理器）：每个线程有一份完整的体系结构状态（通用寄存器、控制寄存器等），缓存、执行部件、控制逻辑等几乎全部资源由两个线程共用；保存状态的晶体管只占很小的比例，超线程增加的芯片面积不到 5%。
图是简化。按 Intel 的优化参考手册（Intel 64 and IA-32 Architectures Optimization Reference Manual，第 049 版，第 2.7 节），实际核心中的硬件分四类。每个线程一份的：除了寄存器与指令指针（即 PC），还有前端的几个小结构（预测 ret 返回地址的小结构、存放取进来的指令字节的小缓冲）与乱序执行中记录各寄存器最新的值在处理器内部哪里的表（本讲不讲）。对半分给两个线程的：各级之间的指令队列、存放等待完成的指令的缓冲区（对应图中的「等待写回」）与读写内存的缓冲区；一个线程停住时，另一个线程仍有自己的一半可用，只有一个线程运行时，这些缓冲区全部给这个线程。两个线程共用的：全部执行部件、缓存与挑选指令执行的部分；执行部件不区分指令属于哪个线程，手册 2012 年版第 2.3.9 节写 Nehalem 时把执行部件列为 HT unaware resources。两个线程轮流用的：取指、译码与指令的完成。所以超线程没有增加执行部件；取指与译码仍是一份，要为两个线程各保存一套状态，并在两个线程之间轮流。
操作系统把支持超线程的一个核心看成两个处理器（Intel 称为逻辑处理器）。i9-11900H 有 8 个核心、每个核心 2 个线程：lscpu 显示 Thread(s) per core: 2、Core(s) per socket: 8，操作系统看到 16 个处理器，第 3 讲 parallel-dot 用的 16 个线程即由此而来；/sys/devices/system/cpu/cpu0/topology/thread_siblings_list 的内容是 0,8，表示编号 0 与 8 的两个处理器是同一个核心的两个线程。
超线程是 Intel 的名称（Hyper-Threading），体系结构教材称同时多线程（simultaneous multithreading，SMT，Tullsen、Eggers 与 Levy，ISCA 1995）；AMD Zen 系列的核心同样每个核心 2 个线程。
学生易错：以为超线程把一个核心变成两个核心。只有 PC 与寄存器堆有两份，执行部件仍是两个，由两个线程共用。
页末的问题：两个线程共用取指、译码与两个执行部件，同一个周期里，两个线程的指令怎样在核心中执行？
""")


def smt_run(p):
    p.title('超线程：两个线程在一个核心中同时执行')
    slide(p, r"""
- **取指轮流**：一个周期按 PC A 取线程 A 的 2 条指令，下一个周期按 PC B 取线程 B 的；
- **执行不分线程**：指令带着线程号等待，执行部件挑操作数就绪的，不论属于哪个线程；
- **写回本线程的寄存器堆**：每个线程的指令按自己的程序顺序写回。
""")
    figure(p, "smt-run", 1120)
    p.notes("""
图与「超线程的硬件结构」一页是同一张硬件图，填上两个线程在周期 8 的指令。每个小格是一条指令，左端的字母是它所属的线程（A 蓝、B 橙）；movl (%rsi…) 是读 x[i] 的 movl (%rsi,%r8,4),%ecx，movl (%rdi…) 是读 w[i] 的 movl (%rdi,%r8,4),%r10d。
设定与「超标量」及乱序执行几页相同：两个执行部件；每个周期取 2 条指令，下一个周期译码；读内存要 3 个周期；执行部件每个周期挑操作数就绪的指令，有多条就绪时先挑取进来最早的，不论属于哪个线程；每个线程按自己的程序顺序写回，每个周期最多写回 2 条。两个线程都执行 dot_product 的循环（各算矩阵的一行），都从第三部分的 movl (%rdi,%r8,4),%r10d 开始：周期 1 取 A 的 movl 与 imull，周期 2 取 B 的 movl 与 imull，此后两个线程轮流取指，译码随之轮流。
逐框看周期 8。取指：这一周期轮到 B，按 PC B 取 B 的 movslq 与读 x[i] 的 movl，是 B 下一轮循环的开头。译码：A 的 movslq 与读 x[i] 的 movl，周期 7 按 PC A 取进来。执行部件：B 的 imull 用 B 在周期 5 至 7 读出的 w[i]（B 的 movl 周期 4 执行），A 的 addl %ecx,%r9d 用 A 在周期 7 算出的乘积，两条属于不同的线程，在同一个周期执行。等待执行的指令：B 的 addl %ecx,%r9d 等 B 的乘积；A 的 jl 与 B 的 cmpl 操作数已经就绪，两个执行部件给了取进来更早的 B 的 imull（周期 2 取指）与 A 的 addl %ecx,%r9d（周期 3 取指），它们等下一个周期；B 的 jl 等 B 的 cmpl 设置标志位。访存：A 的 imull 与 cmpl 周期 7 执行，这一周期经过访存级。等待写回：A、B 的 addl $1,%eax 已经算出，各等本线程中前面的 addl %ecx,%r9d 写回。写回：B 的 movl 把读出的 w[i] 写进线程 B 的 %r10（橙色的箭头与格子）。
下一个周期（周期 9）：取指轮到 A；两个执行部件执行 B 的 addl %ecx,%r9d（用 B 在周期 8 算出的乘积）与 A 的 jl；A 的 imull 把乘积写进线程 A 的 %ecx。
两个线程各用各的寄存器：A 的 addl %ecx,%r9d 读写线程 A 的 %ecx、%r9d，B 的 imull 读写线程 B 的 %r10d、%ecx；寄存器名相同，在硬件上是两个寄存器堆中的不同寄存器，所以两个线程的指令之间没有依赖，转发也只在同一个线程的指令之间进行。
与 Intel 的实现对照（Marr 等 2002）：两个线程都要取指时逐周期轮流，一个线程暂时不能取指时，另一个线程每个周期都可以取；挑选指令执行时不区分线程，同一个周期可以执行两个线程的指令；按程序顺序完成指令时，两个线程轮流。
本页的两处简化。一、2002 年的实现中，取指逐周期轮流，译码器为一个线程连续译码几条指令之后才换到另一个线程，以节省芯片面积、降低复杂度；本页的设定是取指、译码都每个周期轮流。二、图中两个线程等待写回的指令放在同一个虚线框里；实际核心中存放等待完成的指令的缓冲区对半分给两个线程（「超线程的硬件结构」一页讲稿），两个线程的指令仍同在其中。
学生易错一：以为两个线程轮流使用整个核心，一个周期整个核心给 A、下一个周期给 B。轮流的是取指与译码；执行部件在同一个周期可以执行两个线程的指令，图中周期 8 的两个执行部件就是一例。学生易错二：以为两个线程的同名寄存器会互相改写。每个线程有自己的寄存器堆，A 写 %ecx 不改变 B 的 %ecx。
页末的问题：这样执行，一个线程留下的空格有多少能被另一个线程用上？
""")


