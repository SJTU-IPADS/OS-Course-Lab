def llm_what(p):
    p.title('大模型一次生成一个词')
    slide(p, r"""
- 大模型是一个函数：**输入**到目前为止的所有词（token），**输出**下一个词。
- 取出的词追加到输入末尾，再算一次，得到再下一个词。一句回答就是这样一个词一个词生成的。
- 第 6 步的输入里有第 5 步取出的「吞吐」：第 5 步取出词之前，第 6 步==无法开始==。
""")
    figure(p, "llm-autoregressive", 1120)
    p.notes("""
零基础的同学先建立这一个模型：大模型是一个「给定前文、算出下一个词」的函数。词（token）是模型处理的基本单位，可能是一个汉字、一个词、一个英文单词或它的一部分；Qwen3-VL-2B 的词表有 151936 个候选。模型对每个候选给出一个概率，图中的条形示意这个分布，通常取概率最大的那个（也可以按概率抽样）。
配图的两行是相邻两步：第 5 步输入「流水线 提高 的 是」四个词，取出「吞吐」；「吞吐」追加到末尾成为第 6 步的第 5 个输入，第 6 步取出「率」。例句就是本讲的结论「流水线提高的是吞吐率」。
这里埋下第四部分最重要的一条线：第 6 步的输入要用第 5 步的输出，所以第 6 步必须等。这和第 2 部分「后一条指令要用前一条的结果」是同一种依赖，后面讲流水线并行的气泡与投机推理都从这里出发。
学生易错：以为模型一次就把整句话写出来。模型每算一次只多出一个词，一句 50 个词的回答要算 50 次。
页末的问题：模型内部「算一次」要做什么？
""")


def llm_layers(p):
    p.title('算一次：向量依次穿过 28 层')
    slide(p, r"""
- 输入的词先变成一个向量（Qwen3-VL-2B：2048 个数）。
- 向量穿过第 1 层、第 2 层……第 28 层，每一层的主要工作是**权重矩阵 × 向量**。
- 第 28 层的输出算出每个候选词的分数，取词。28 层的权重共 17.2 亿个，Q4_0 存成 0.968 GB，每生成一个词==全部读一遍==。
""")
    figure(p, "llm-layers", 1120)
    p.notes("""
一层里面还有注意力、前馈网络等结构，本讲只需要知道：每一层有自己的一组权重矩阵，层的主要工作是用这些矩阵乘以进来的向量，输出一个同样 2048 个数的向量交给下一层。
28 层是 Qwen3-VL-2B 的实际层数；17.2 亿个权重按 4 位量化（Q4_0，平均每个权重约 4.5 位）存成 0.968 GB。每生成一个词，向量要从第 1 层走到第 28 层，28 层的权重全部读一遍。
学生易错：以为 28 层是同一组权重用 28 次。每一层的权重各不相同，所以总量是 28 层相加。
页末的问题：0.968 GB 一块 GPU 放得下。更大的模型呢？
""")


def llm_too_big(p):
    p.title('一块 GPU 装不下的模型')
    slide(p, r"""
- GPU 用自己的**显存**存放权重。一块 H100 的显存是 80 GB。
- Llama 3.1 405B 有 4050 亿个权重，每个 16 位（2 字节），共 810 GB：810 ÷ 80 ≈ 10.1，至少 ==11 块 GPU== 才放得下。
- 权重必须分散到多块 GPU 上。怎么分？
""")
    figure(p, "llm-too-big", 1120)
    p.notes("""
GPU 的运算单元只能直接访问自己的显存，权重必须先放进显存才能参与计算。H100 的 80 GB 是当前数据中心常见的一档；405B 这种规模的模型，光是权重就是显存的十倍以上，还没算推理时的中间结果。实际部署通常用 16 块 GPU、两台机器。
配图把 810 GB 的长条按 80 GB 一格划开，数格子就能看出需要几块 GPU：10 格满了还多出一截。
分法有两种。一种是按层切：前几层放一块 GPU，后几层放下一块，这就是本节要讲的流水线并行。另一种是把每一层的矩阵本身切开，几块 GPU 各算矩阵的一部分再合并（张量并行），每一层都要在 GPU 之间交换数据，这里只提名字。
页末的问题：按层切开后，一个请求怎样跑完 28 层？
""")


def llm_split(p):
    p.title('按层切开：流水线并行')
    slide(p, r"""
- 把 28 层切成 4 份，每份 7 层，放在 4 块 GPU 上。
- 一个请求的向量先在 GPU 1 穿过第 1–7 层，结果（一个 2048 个数的向量）发给 GPU 2，再穿过第 8–14 层……到 GPU 4 取词。
- 四块 GPU 就是四级，GPU 之间传的向量就是第 8 页==级间寄存器==里的内容。这种切法叫==流水线并行==。
""")
    figure(p, "llm-split", 1120)
    p.notes("""
与第 1 部分对照：那里一条指令依次经过取指、译码、执行、访存、写回五组硬件，这里一个请求依次经过四块 GPU；那里相邻两级之间用级间寄存器保存结果，这里 GPU 1 算完把向量通过显卡之间的连线发给 GPU 2。要传的只是一个 2048 个数的向量（几 KB），比每块 GPU 自己要读的几百 MB 乃至几十 GB 权重小得多，所以切开是划算的。
Qwen3-VL-2B 只有 0.968 GB，一块 GPU 放得下，图里切成 4 份是为了用熟悉的 28 层来画；真正需要切的是上一页那样的大模型，道理相同。
流水线并行（pipeline parallelism）的名字来自 GPipe（Huang 等，NeurIPS 2019）和 PipeDream（Narayanan 等，SOSP 2019），两篇论文讲的是训练，推理服务的切法相同。
页末的问题：只有一个请求时，四块 GPU 同时在忙吗？
""")


def llm_pp_single(p):
    p.title('一个请求：每一拍只有一块 GPU 在算')
    slide(p, r"""
把四块 GPU 画成时空图的四行，一拍是一块 GPU 处理 7 层的时间。

只跑 1 个请求时，第 1 拍只有 GPU 1 在算，GPU 2、3、4 在等它的结果；第 2 拍轮到 GPU 2，其余三块又在等。这些==停==格就是==气泡==：16 格里 12 格是停。
""")
    figure(p, "llm-pp-single", 1120)
    p.notes("""
这张图和第 8 页「流水线原理」的硬件视角相同：一行是一组硬件（这里是一块 GPU），色块是它为某个请求工作的时间，停格是它空闲的时间。4 块 GPU × 4 拍共 16 个格子，只有 4 个在算，利用率 1/4。花钱买了 4 块卡，3 块在大部分时间里闲着。
这和「单周期实现」是同一个问题：一条指令走完五级再放下一条，五组硬件里总有四组空着。解决的思路也相同：让后面的请求跟着进来。
学生易错：以为切成 4 块 GPU 就能让这 1 个请求快 4 倍。这 1 个请求仍要依次走过 4 块 GPU，总耗时没有变短，还多了卡间传输的时间。
页末的问题：怎样把这 3 块空闲的 GPU 用起来？
""")


def llm_pp_fill(p):
    p.title('多个请求跟着进来')
    slide(p, r"""
- 请求 1 传给 GPU 2 的同时，GPU 1 接下请求 2；再下一拍接请求 3。第 4 拍起 4 块 GPU 同时在算，各算一个不同的请求。
- 每个请求自己仍要走 4 拍（**延迟**不变），每一拍完成的请求变多（**吞吐**提高）：与第 1 部分的流水线时空图同一形状。
""")
    p.frames("assets/llm-pp-fill-1.svg", "assets/llm-pp-fill-2.svg", "assets/llm-pp-fill-3.svg",
             "assets/llm-pp-fill-4.svg", width_px=1120)
    p.notes("""
这一页有 4 帧：第 1 帧只有请求 1 进入 GPU 1；第 2 帧请求 1 到了 GPU 2，请求 2 进入 GPU 1；第 3 帧跳到第 4 拍，4 块 GPU 各算一个请求，橙框标出这一列；第 4 帧补齐到第 7 拍，红括号标出两头的气泡：填满后每一拍完成一个请求，开头和结尾仍有气泡。
与第 9 页「流水线时空图」逐项对照：那里周期 5 五级同时有指令、从周期 5 起每周期写回一条；这里周期 4 四块 GPU 同时有请求、从周期 4 起每拍完成一个请求。一条指令仍要 5 个周期，一个请求仍要 4 拍。
请求从哪里来：线上服务同时有许多用户在提问，每个用户的请求是独立的；训练时则把一大批数据切成许多小批依次送入。两种情况在图上画法相同。
学生易错：以为填满之后就没有气泡了。看第 4 帧：第 1–3 拍后面的 GPU 还没拿到请求，第 5–7 拍前面的 GPU 已经没有新请求，这两处红格填不掉。
页末的问题：两头的气泡占多大比例？
""")


def llm_pp_ratio(p):
    p.title('进管与排空的气泡占多大')
    slide(p, r"""
- 4 块 GPU（K = 4）连续处理 8 个请求（M = 8）：共 4 × 11 = 44 格，气泡 12 格，占 27%。一般地，==气泡占比 = (K − 1) ÷ (M + K − 1)==。
- 连续排进去的请求越多，两头的气泡占比越小；切的块数 K 越多，气泡越多。
""")
    p.table([
        ['气泡占比（K = 4）', '3 ÷ 7 = 43%', '3 ÷ 11 = 27%', '3 ÷ 19 = 16%', '3 ÷ 35 = 9%'],
    ], headers=['连续请求数', 'M = 4', 'M = 8', 'M = 16', 'M = 32'], widths=[24, 19, 19, 19, 19])
    figure(p, "llm-pp-ratio", 1120)
    p.notes("""
数格子：上面的图 4 行、11 列。请求 1 占第 1–4 列的对角线，请求 8 占第 8–11 列，左下和右上各有一个 1+2+3 = 6 格的三角形是停，共 12 格；12 ÷ 44 = 27%。换成字母：行数 K，请求数 M，总列数 M + K − 1，气泡格数 K(K − 1)，占比 K(K − 1) ÷ [K(M + K − 1)] = (K − 1) ÷ (M + K − 1)。GPipe 论文（Huang 等，NeurIPS 2019）给出的就是这个比例。
表格读法：K = 4 固定，连续请求数翻倍，气泡占比大约减半。要把气泡压到 10% 以下，连续的请求数要达到 GPU 块数的十倍左右。反过来，一个模型若被切成 16 块 GPU（K = 16），同样的请求数下气泡占比是 K = 4 时的好几倍，所以切的块数以够放下权重为限，而不是越多越好。
与第 10 页「流水线加速上限」对照：那里说级数切得越细、级间寄存器开销占比越高；这里说切的块数越多、两头的气泡占比越高。两处都在说「级数不是越多越好」。
页末的问题：这些请求从哪来？一个用户逐词生成时，他的下一个词什么时候能进入 GPU 1？
""")


def llm_pp_decode(p):
    p.title('逐词生成：下一个词要等 GPU 4 取词')
    slide(p, r"""
- 词 1 在第 4 拍于 GPU 4 取出；它是词 2 的输入，词 2 第 5 拍才能进入 GPU 1。
- 第 2、3、4 拍 GPU 1 没有这个请求的新词可做。只有一个请求时，每一拍仍只有一块 GPU 在算。
- 这就是第 2 部分的 data hazard：后一个任务的输入是前一个任务的输出，中间只能==停==。
""")
    figure(p, "llm-pp-decode", 1120)
    p.notes("""
把第一页「大模型一次生成一个词」的依赖画到时空图上：词 2 的输入里要有词 1，而词 1 要到 GPU 4 做完取词才存在。图中的箭头从 GPU 4 第 4 拍的词 1 指向 GPU 1 第 5 拍的词 2，中间隔着的三拍 GPU 1 只能停。与第 14 页「读内存后马上使用」对照：那里 imull 要等 movl 的访存结束，这里词 2 要等词 1 的取词结束；那里停一拍，这里停三拍（GPU 2、3、4 各一拍）。
所以一个用户独自逐词生成时，4 块 GPU 的流水线和 1 块 GPU 一样慢：生成 8 拍只出 2 个词。
提示词里的词都是已知的，它们之间没有这种依赖，可以像上两页那样一拍一个连续进入，这就是 prefill 快、逐词生成（decode）慢的原因之一。实测（examples/llm_stages.py）：提示词 1455.8 词/秒，逐词生成 190.2 词/秒。
学生易错：以为出现气泡时 GPU 坏了或在空转耗电。GPU 只是没有可算的输入；下一节讲把别的用户的词填进去。
页末的问题：别的用户的请求需要等这个词吗？
""")


def llm_pp_batch(p):
    p.title('多个用户的请求轮流进入')
    slide(p, r"""
- 请求 2 的词不依赖请求 1 的词，第 2 拍就能进入 GPU 1；请求 3、4 依次跟上。
- 请求 1 的词 1 在第 4 拍取出，它的词 2 恰好在第 5 拍进入 GPU 1：4 个请求轮流，第 4 拍起==没有气泡==。
- 每个请求自己仍是 4 拍出一个词；服务器每拍出一个词。独立的请求数至少等于 GPU 块数，流水线才填得满。
""")
    figure(p, "llm-pp-batch", 1120)
    p.notes("""
对照上一页：上一页只有一个请求，GPU 1 在第 2、3、4 拍停着；这一页请求 2、3、4 的词填进了这三拍，它们各自不需要请求 1 的结果。请求 1 的词 1 在第 4 拍从 GPU 4 取出，正好在第 5 拍回到 GPU 1 排进它的词 2，每块 GPU 从第 4 拍起一直有事做。
与第 2 部分讲稿里的那句是同一件事：movl 与 imull 之间若能插进一条不依赖该结果的指令，停的那一拍就有事做；编译器做的是指令调度，这里服务器做的是把不同用户的请求排在一起（连续批处理，Orca，OSDI 2022：一个请求结束，新来的请求立刻补进空出的位置）。
两个数字的区别：每个用户看到的仍是 4 拍一个词（延迟），服务器总共每拍出一个词（吞吐）。流水线提高的是吞吐。
学生易错：以为批处理让一个请求自己的下一个词提前开始。下一个词的输入仍是它自己取出的词，等的时间没变，变的是等的期间 GPU 在为别人工作。
页末的问题：一个用户独自使用时，下一个词非等 GPU 4 算完不可吗？能不能像分支预测那样先猜？
""")


def llm_decode_slow(p):
    p.title('逐词生成慢在哪：每个词都要读一遍全部权重')
    slide(p, r"""
- 生成一个词要把全部权重读一遍：Qwen3-VL-2B 每个词读 0.968 GB，读权重的遍数决定了速度。
- 几个词的输入都已知时，权重仍只读一遍，每个权重服务几个向量：提示词实测 1455.8 词/秒，逐词生成 190.2 词/秒。
- 一遍权重若能同时算出多个位置，就省了好几遍读权重。可是==后面的词还没取出来==。
""")
    figure(p, "llm-read-once", 1120)
    p.notes("""
生成一个词的时间下限是权重字节数除以显存带宽：权重要从显存搬到运算单元，搬一遍要多久，一个词就至少要多久。配图左边是逐词生成：一个向量进去、一个词出来，权重读一遍；右边是提示词那样几个词的输入都已知：四个向量一起进去，权重仍只读一遍，同时得到四个词。实测两者相差约 8 倍（examples/llm_stages.py，2026-10-07，RTX 3060 Laptop，Qwen3-VL-2B Q4_0：提示词 393 个词 270.0 ms，生成 59 个词 310.1 ms）。
多算几个位置为什么几乎不花时间：读权重占了绝大部分时间，运算单元大多在等数据；多送几个向量进去，只是让已经读进来的权重多乘几次，运算单元有的是空闲。
所以问题变成：逐词生成时，能否也一次送进多个位置？障碍只有一个，后面的词的输入还没取出来。
页末的问题：后面的词还不知道，能先猜吗？
""")


def llm_spec_idea(p):
    p.title('先猜：用一个小模型连猜几个词')
    slide(p, r"""
- 找一个小得多的模型（权重少几十倍，读一遍很快），接着前文连猜 4 个词。
- 小模型不够准，但快；常见的词（「的」「是」、固定搭配、代码里的括号）它多半能猜对。
- 第 2 部分的分支预测也是这样：`jl` 的方向还没算出来，先按猜测取指。这里是词还没取出来，==先按猜测往后排==。
""")
    figure(p, "spec-guess", 1120)
    p.notes("""
小模型（草稿模型，draft model）通常是同系列里参数量小一到两个数量级的模型，例如用 1B 的模型给 70B 的模型打草稿。它读一遍自己的权重只要大模型的几十分之一时间，所以连猜 4 个词的时间仍远少于大模型算 1 个词。
猜的词只是候选，最终用不用由大模型说了算（下一页）。所以小模型猜错不影响正确性，只影响速度。
与分支预测的对应：CPU 不知道 jl 跳不跳，不等结果就按预测方向取下一条指令；这里不知道下一个词是什么，不等大模型就先用小模型的猜测往后排。两边都把「等结果」换成了「先猜、后验证」。
学生易错：以为小模型在替大模型回答。小模型只负责提供候选，每个留下的词都要经过大模型核对。
页末的问题：怎样一次核对这 4 个猜测？
""")


def llm_spec_verify(p):
    p.title('核对：大模型读一遍权重，同时检查 4 个位置')
    slide(p, r"""
- 把前文和猜出的 4 个词一起送进大模型，像提示词那样一次穿过 28 层，每个位置得到大模型自己会取的词。
- 从前往后比对：猜对的接受；第一个猜错的位置换成大模型的词；它后面的猜测全部==作废==。
- 这一轮接受「吞」「吐」，改为「率」，作废「，」：读一遍权重得到 ==3 个词==。
""")
    figure(p, "spec-decode", 1120)
    p.notes("""
核对为什么只要读一遍权重：上上页的右半边。猜出的 4 个词现在是已知输入，连同前文一起送进去，大模型在一次前向计算里得到 4 个位置的输出——位置 1 的输出是「接着前文该取什么」，位置 2 的输出是「接着前文加猜 1 该取什么」，依此类推。
比对规则：位置 1 大模型取「吞」，与猜 1 相同，接受；位置 2 取「吐」，接受；位置 3 大模型取「率」，小模型猜的是「量」，用大模型的「率」；位置 4 的猜测「，」建立在错误的「量」之上，作废。这一轮前进 3 个词，逐词生成要读 3 遍权重。即便猜 1 就错，大模型也已经算出了位置 1 的正确词，至少前进 1 个。
投机推理（speculative decoding）：Leviathan 等，ICML 2023；Chen 等（DeepMind），2023。两篇论文证明，若按概率抽样而非取最大，只要按一个特定的概率接受或拒绝猜测，输出的分布与大模型逐词生成完全相同。课堂上按「取概率最大的词」讲，结论最直观：输出逐字相同。
学生易错：以为作废会浪费大模型的工作。作废的只是小模型的候选，大模型在该位置算出的词仍然用上了。
页末的问题：猜错作废会不会弄坏结果？和 CPU 的分支作废有什么异同？
""")


