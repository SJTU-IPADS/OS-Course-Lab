    path = pathlib.Path(__file__).resolve().parent / "diagrams" / "mountain.txt"
    table = {}
    for line in path.read_text(encoding="utf-8").splitlines()[1:]:
        fields = line.split()
        table[fields[0] + fields[1]] = [float(v) for v in fields[2:]]
    return table


