def spatial_cache(p):
    p.title("空间局部性与缓存")
    p.gap(24)
    slide(p, r"""
- 程序通常具有**空间局部性**：访问一个存储位置后，往往很快访问其邻近位置。
- CPU 设计据此引入**缓存**，把访问的数据及其邻近数据一起放入较小、较快的存储空间。
""")
    figure(p, "spatial-cache", 1000)
    slide(p, r"""
- 将一段连续数据作为一个**块**取入缓存。块仍在缓存中时，对其中相邻元素的后续访问可以直接由缓存提供。
""")
    p.highlight("缓存利用空间局部性，减少对较慢存储的访问。")
    p.notes("""
空间局部性描述访问的地址关系：访问一个元素后，地址相邻的元素也可能很快被访问。sum_rows 连续读取一行中的元素，具有良好的空间局部性。
图中一个块含同一行的 4 个 int。读取 W[i][0] 时，把 W[i][0] 至 W[i][3] 一起取入缓存。只要这个块仍在缓存中，读取 W[i][1]、W[i][2]、W[i][3] 时就可以直接从缓存取得数据。图中的块长只用于说明原理。
软硬件设计都可以利用空间局部性。硬件缓存把连续地址的数据一起取入，软件也可以一次读取并保留文件中相邻的一段数据。把空间上相邻的数据一起保存，使一次较慢的读取能够服务多次访问。
""")


# 上一页说明缓存怎样利用空间局部性。本页用静态结构图给出 CPU 内部的寄存器与缓存、外部的内存、访问延迟和传输单位。
def cache_between(p):
    p.title("CPU 与内存之间的缓存")
    slide(p, r"""
- **寄存器**与**缓存**都位于 CPU 内部，内存位于 CPU 外部。
- 缓存与内存之间以**块**为单位传输，块是内存中起始地址对齐、长度固定的一段连续字节。
- 缓存保存内存的一部分块，供 CPU 快速访问。
""")
    figure(p, "cache-between", 900)
    p.notes("""
CPU 的读写请求以字为单位，字长 1 至 8 字节。缓存与内存之间的传输以块为单位，一个块通常是 64 字节。
CPU 外框内包含寄存器与缓存，内存位于 CPU 外部。图中的两条连接分别位于寄存器与缓存之间、缓存与内存之间。
连接箭头上方用取整后的数字与单位标出 CPU 取得所需数据的访问延迟数量级：缓存约为 1–50 ns，内存约为 100 ns。这些数值用于教学示意，具体时延随硬件和访问条件变化。内存的时间包含 CPU 等待取到数据的完整过程。
数值参考 Intel 的 Memory Performance in a Nutshell 与 Arm 的 About memory latency。前者给出约 1 ns、4 ns 与 40 ns 的缓存访问示例，后者给出约 100 ns 的内存访问示例。
缓存的容量远小于内存，只能保存内存的一部分块。
""")


# 上一页给出 CPU、缓存与内存的关系。本页保留结构图，补充按块取入、放置策略与替换策略。
def cache_features(p):
    cache_between(p)
    slide(p, r"""
- **按块取入**：数据未缓存时，即使只需要一个字节，也会取入整个块，相邻字节提前取入。
- **放置与替换策略**：放置策略决定新取入的块应该放在哪些位置，替换策略决定当这些位置无空闲时应该逐出哪个旧块。
""")
    p.notes("""
CPU 读取一个未缓存的字节时，将其所在的整个块从内存取入缓存，同一块内的相邻字节也随之进入缓存，后续访问可以利用这些数据。这一按块取入的机制利用了空间局部性。
放置策略规定一个内存块可以放入缓存中的哪些位置。需要取入新块时，先在这些候选位置中寻找空位。候选位置已满时，替换策略决定逐出其中哪个旧块，为新块腾出位置。
""")


# 上一页给出缓存的按块取入、放置与替换。本页从容量差距引出按需取入，并定义一次访问的 hit 与 miss。
def cache_hit_miss(p):
    p.title("hit 与 miss")
    slide(p, r"""
- 内存容量远大于缓存，无法全部放入缓存，因此缓存采取按需取入的方式，响应 CPU 的访问请求取入数据块。
- **hit**：块已在缓存中，直接把所需的数据返回给 CPU。
- **miss**：块不在缓存中，从内存取入整个块，再把所需的数据返回给 CPU。
""")
    p.frames(*(f"assets/cache-hit-miss-{k}.svg" for k in (1, 2, 3)), width_px=900)
    p.notes("""
图中寄存器与缓存都位于 CPU 内部，内存位于 CPU 外部。内存容量远大于缓存，所有数据无法同时放入缓存，CPU 访问时才把所需的块取入。
三帧依次是：请求的字所在的块已在缓存中，直接返回，称为 hit。请求的块不在缓存中，向内存请求整个块，称为 miss。取回的块放入缓存，必要时替换已有的块，再把所需的字返回 CPU。
放置策略与替换策略决定新块保存在哪里、已有的哪个块被逐出。miss 需要访问较慢的内存，通常比 hit 花费更长的时间。
""")


# 上一页给出 hit 与 miss。本页用一个小缓存演示：按行遍历 W[4][4]，每次读取的元素在缓存中的哪个块里，
