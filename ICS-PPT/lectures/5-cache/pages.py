# 第一页：回答“什么样的访问序列 hit 率高”，给出三条规则，并用同一个数组的两种遍历顺序对照。
def friendly_rules(p):
    p.title("缓存友好的代码")
    slide(p, r"""
缓存友好的代码使访问序列有局部性，遵循三条规则：
1. **内层循环**：它的循环体执行的次数最多，它的访问是否 hit 影响最大。
2. **重复引用同一变量**（时间局部性）：局部变量放在寄存器中，其余变量在第一次引用之后留在缓存中。
3. **以步长 1 按存放顺序引用数据**（空间局部性）：一个块内的元素依次被使用，每个块只有第一次引用 miss。
""")
    columns(p, "```c\n" + SUM_ROWS + "\n```", "```c\n" + SUM_COLS + "\n```")
    slide(p, r"""
`sum_rows` 的内层循环以步长 1 引用 `W[i][j]`，`sum_cols` 的步长为 $N$ 个元素。
""")
    p.notes("""
本部分回答的问题是：缓存的参数固定之后，什么样的访问序列 hit 率高。三条规则是这个问题的答案，其余的页检验它们并给出定量的结果。
第一条规则的理由是次数：一个二重循环中，内层循环体的执行次数是外层的 N 倍，一次 miss 的代价乘上这个次数。
第二条规则：局部变量 sum 与 i 放在寄存器中，引用它们不访问内存。数组元素的重复引用靠缓存，第一次 miss，之后 hit。
第三条规则：数组按行存放，W[i][j] 与 W[i][j+1] 相邻。内层循环 j 变化时步长为 1，一个块中的各元素依次被用到。内层循环 i 变化时，相邻两次访问相差 N 个元素，每次访问落在不同的块中。
两个函数的运算次数相同，访问的元素相同，只有访问的次序不同。
""")


SUM_ROWS = """int sum_rows(int W[M][N]) {
    int sum = 0;
    for (int i = 0; i < M; i++)
        for (int j = 0; j < N; j++)
            sum += W[i][j];
    return sum;
}"""

SUM_COLS = """int sum_cols(int W[M][N]) {
    int sum = 0;
    for (int j = 0; j < N; j++)
        for (int i = 0; i < M; i++)
            sum += W[i][j];
    return sum;
}"""


# 上一页说步长为 1 时一个块内的元素依次被使用。本页把它量化：步长为 k 的遍历，每个块有几次访问，miss 率是多少。
def friendly_miss_rate(p):
    p.title("步长与 miss 率")
    slide(p, r"""
步长为 $k$ 个元素的遍历，块为 $B$ 字节，元素为 4 字节：每个块被访问 $B / (4k)$ 次，其中只有第一次 miss，miss 率为 $\min(1, 4k / B)$。图中 $B = 64$，一个块容纳 16 个 int。
""")
    slide(p, r"""
估算假设数组的起点与块对齐，缓存起初为空，数组远大于缓存。
""")
    p.image("assets/friendly-miss-rate.svg", width_px=1100, alt="步长 1、2、4、8、16 的遍历在一个 64 字节的块内分别访问 16、8、4、2、1 次，只有块内的第一次访问 miss，miss 率分别为 1/16、1/8、1/4、1/2、1")
    p.notes("""图中每行是同一个 64 字节的块（16 个 int）中被访问的元素，格中的数字是访问的次序。红色的是块内的第一次访问，绿色的是块内的其他访问，白色的元素不被访问。步长 k 的遍历访问 W[0]、W[k]、W[2k]……每次前进 4k 字节。
步长 1：块内 16 个元素依次被访问，只有第 1 次 miss，其余 15 次 hit，miss 率 1/16。
步长 2：块内访问 8 次，miss 率 1/8。
步长 4：块内访问 4 次，miss 率 1/4。
步长 8：块内访问 2 次，miss 率 1/2。
步长 16：相邻两次访问相差 64 字节，每个块只访问 1 次，每次访问都 miss，miss 率 1。k 大于 16 时仍然每次访问都 miss，所以 miss 率取 min(1, 4k/B)。
三条假设各有作用：起点对齐保证一个块从第一个元素算起。缓存起初为空保证每个块的第一次访问 miss。数组远大于缓存保证遍历结束前，已用过的块不会再被用到，也就没有因重复访问产生的 hit。
""")


