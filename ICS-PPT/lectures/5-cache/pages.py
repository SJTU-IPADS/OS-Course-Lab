# 起点问题：缓存中的数据被写入时怎样处理，一个缓存的好坏用什么衡量。
# 与上一部分的关系：上一部分对矩阵的只读访问计算miss rate，并分析了同组块的复用。
# 那里的访问都是读，读不改变缓存与下一层的一致性。程序同样要写，写使缓存中的副本与下一层
