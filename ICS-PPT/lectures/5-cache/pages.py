# 第一页：用多级缓存的一次写说明问题，写入使各层的副本不一致，新值还可能随替换丢失。
def write_problem(p):
    p.title("写入的一致性问题")
    slide(p, r"""
缓存分多级，每一级保存内存中一部分块的副本。写入一个字时，各层的副本怎样更新？
""")
    p.frames(*(f"assets/write-problem-{k}.svg" for k in range(1, 6)), width_px=1000)
    slide(p, "写入之后，新值必须在某个时刻更新到下一层。")
    p.notes("""
图中自上而下是处理器、L1、L2 与内存。橙色是刚写入的副本，红框是旧值。
第一帧：x 的块在每一层都有一份副本，值是 1。读不会改变副本，三层的值一致。
第二帧：处理器写 x = 2。该块在 L1 中。
第三帧：L1 更新自己的副本，L2 与内存中的 x 仍是 1，三份副本不一致。
第四帧：L1 要装入别的块，把这一行替换出去。如果替换时直接丢弃，新值 2 在任何一层都不存在。
第五帧：再读 x，L1 miss，从 L2 取得的是 1，程序读到的不是它写入的值。因此写入之后，必须在某个时刻把新值更新到下一层。
""")


# 上一页的问题是新值必须更新到下一层。最朴素的做法是写入时立即更新，本页给出这种做法与它的代价。
def write_through(p):
    p.title("写 hit：写直达")
    slide(p, r"""
处理器写入的地址所在的块已在缓存中，称为**写 hit**。

最朴素的做法是**写直达**（write-through）：每次写 hit，在更新缓存的同时把这个字写到下一层，各层始终一致，被替换的行直接丢弃。
""")
    p.frames(*(f"assets/write-through-{k}.svg" for k in range(1, 5)), width_px=1000)
    p.notes("""
图右侧一列是每一层被写入的次数。一个箭头表示传送一个字。
第一帧：处理器写 x = 2，该块在 L1 中，写 hit，L1 更新 x。此时 L2 与内存仍是旧值。
第二帧：L1 同时把这个字写到 L2。
第三帧：L2 同时把这个字写到内存，三份副本一致。行与下一层一致，不需要额外状态，被替换时丢弃即可。
第四帧：代价是每次写都要传到内存。同一个字写 100 次，内存被写 100 次，处理器的每次写都要等内存写完。
""")


# 上一页的写直达每次写都等内存。本页把更新推迟到行被替换时：写 100 次，内存只被写 1 次。
def write_back(p):
    p.title("写 hit：写回")
    slide(p, r"""
**写回**（write-back）只更新缓存，下一层的更新推迟到该行被替换时：
- 每行增加一位**脏位**（dirty bit）：行被写过则 D = 1，表示它与下一层的副本不同。
- 被替换时，D = 1 的行整块写到下一层，D = 0 的行直接丢弃。
""")
    p.frames(*(f"assets/write-back-{k}.svg" for k in range(1, 5)), width_px=1000)
    p.notes("""
图中每行多了一列脏位 D。四个并排的箭头表示传送整个块。
第一帧：处理器写 x = 2，写 hit。只更新 L1，脏位 D 置 1。L2 与内存仍是旧值。
第二帧：同一个字再写 99 次，每次只更新 L1，不写下一层。
第三帧：L1 替换这一行。D = 1，把整个块写到 L2，L2 这一行的 D 置 1。
第四帧：L2 替换这一行。D = 1，把整个块写到内存。同一个字写 100 次，内存只被写 1 次。
D = 0 的行与下一层一致，替换时直接丢弃。
""")


# 上一页给出写 hit 的两种做法。本页转到写的块不在缓存中的情况，先给出取块的做法，并与写回搭配。
def write_allocate(p):
    p.title("写 miss：写分配")
    slide(p, r"""
处理器写入的地址所在的块不在缓存中，称为**写 miss**。**写分配**（write-allocate）先把该块从下一层取入缓存，再按写 hit 处理。
""")
    p.frames(*(f"assets/write-allocate-{k}.svg" for k in range(1, 5)), width_px=1000)
    slide(p, "写回通常配写分配：写过的块留在缓存中，后续的读与写 hit。")
    p.notes("""
第一帧：处理器写 x = 2，L1 中的这一行无效，写 miss。
第二帧：把该块从 L2 取入 L1，四个绿色箭头表示整个块。
第三帧：按写 hit 处理。下一层何时更新由写 hit 的策略决定，图中是写回：更新 L1 的 x，D 置 1。
第四帧：之后对这个块的读写都在 L1 中 hit。写过的数据常常随后被读到，相邻的元素常常紧接着被写，写分配利用了这两种局部性，因此写回通常配写分配。
""")


# 上一页的写分配为一次写取入整个块。本页给出不取块的做法，它与写直达搭配。
def no_write_allocate(p):
    p.title("写 miss：非写分配")
    slide(p, r"""
**非写分配**（no-write-allocate）不取块，直接把这个字写到下一层。
""")
    p.frames(*(f"assets/no-write-allocate-{k}.svg" for k in range(1, 5)), width_px=1000)
    slide(p, "写直达通常配非写分配：写已到达下一层，无需取块。")
    p.notes("""
第一帧：同样的起点，处理器写 x = 2，L1 中的这一行无效，写 miss。
第二帧：不取块，这个字绕过 L1 写到 L2，L1 不变。
第三帧：下一层何时更新由写 hit 的策略决定，图中是写直达：L2 同时把这个字写到内存。
第四帧：之后读 x，L1 中没有该块，读 miss，这时才从 L2 取块。
写直达每次写都已经到达下一层，缓存里有没有这个块不影响正确性，不取块可以省去一次块的传输，因此写直达通常配非写分配。
写 miss 的两种做法与写 hit 的两种做法各自独立，实际使用时成对出现。
""")


# 上一页给出写的处理。本页给出一级缓存的结构：指令与数据分开存放，各有各的缓存。
