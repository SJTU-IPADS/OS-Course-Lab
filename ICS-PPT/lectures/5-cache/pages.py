def code2(p, left, right):
    return columns(p, "```c\n" + left + "\n```", "```c\n" + right + "\n```")


def matmul_def(p):
    p.title("矩阵乘法")
    slide(p, r"""
矩阵乘法 $C = AB$：$C_{ij} = \sum_{k} A_{ik} B_{kj}$，即 $C$ 的第 $i$ 行第 $j$ 列的元素是 $A$ 的第 $i$ 行与 $B$ 的第 $j$ 列的内积。三个 $n \times n$ 的 double 矩阵按行存放：
""")
    figure(p, "matmul-def", 1000)
    slide(p, r"""
分析假设：$n$ 很大，缓存容纳不下一列所在的 $n$ 个块，块为 64 字节，放 8 个 double。

三个循环变量可以按任意次序嵌套，共六种顺序，按内层循环的变量分为三类。
""")
    p.notes("""
矩阵乘法的运算次数是 n 的三次方：C 的 n² 个元素，每个元素 n 次乘加。三重循环的三个循环变量 i、j、k 可以按任意次序嵌套，共 6 种，运算与结果相同，访问的次序不同。
A[i][k]、B[k][j] 与 C[i][j] 在内存中都按行存放：同一行相邻的元素相邻，同一列相邻的元素相差 n 个 double。
分析假设中，块 64 字节放 8 个 double。n 很大使得缓存容纳不下一列所在的 n 个块：沿一列访问 B 时每次落在不同的块中，当同一列的下一个元素到达时这个块已被替换，沿列访问的每次引用都 miss。图中橙色是计算 C[i][j] 用到的元素。
六种顺序按内层循环变量分成三类，每类有两种写法。
""")


