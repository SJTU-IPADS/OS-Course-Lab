def metrics(p):
    p.title("缓存的性能指标")
    slide(p, r"""
- **miss 率** $m$ = miss 的访问数 / 全部访问数，**hit 率** = 1 − $m$。
- **hit 时间** $t_{hit}$：hit 时把数据送到处理器的时间，包括判断是否 hit 的时间。
- **miss 惩罚** $t_{pen}$：miss 时比 hit 多出的时间，即从下一层取得块、放入缓存并把数据送到处理器的时间。
""").footnote(METRICS_NOTE)
    with p.flex("row", valign="middle"):
        p.table(
            headers=["层", "hit 时间", "miss 惩罚"],
            rows=[["L1", f"{LAT_L1} ns", f"{PEN_L1} ns"],
                  ["L2", f"{LAT_L2} ns", f"{PEN_L2} ns"],
                  ["L3", f"{LAT_L3:.1f} ns", f"{PEN_L3} ns"]],
            align=["left", "right", "right"],
        )
        figure(p, "metrics-time", 560)
    p.highlight(r"平均访存时间 $= t_{hit} + m \times t_{pen}$")
    p.notes("""
定义要写准。miss 率与 hit 率针对一段执行或一个访问序列统计。hit 时间包含判断 hit 所用的时间，因为不论 hit 与否都要先判断。miss 惩罚是 miss 时多出的时间，不含 hit 时间。
表中的 hit 时间取各层的访问延迟。miss 惩罚取相邻两层访问延迟之差：L1 miss 后由 L2 提供数据，总时间是 3.1 ns，比 L1 hit 多出 2.0 ns。L3 miss 后由内存提供数据，多出 114.5 − 12.0 = 102.5 ns。右图按比例画出 L1 的一次 hit 与一次 miss。
平均访存时间的公式直接来自这些定义：所有访问都花费 hit 时间 t_hit，其中比例为 m 的访问再花费 miss 惩罚 t_pen。
""")


